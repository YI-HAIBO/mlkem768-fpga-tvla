// =========================================================================
// Input coefficient buffering (asynchronous writes)
// =========================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // buffers not cleared at reset (expensive for 256 entries)
    end else begin
        if (a_wr) buf_a[a_addr] <= a_data;
        if (b_wr) buf_b[b_addr] <= b_data;
    end
end

// =========================================================================
// Pointwise NTT-domain multiplication (standard multiplication, not fqmul)
// =========================================================================
assign mul_a_u    = from_signed_23($signed(ram_a_ntt[idx]));
assign mul_b_u    = from_signed_23($signed(ram_b_ntt[idx]));
assign mul_prod   = mul_a_u * mul_b_u;
assign mul_result = mod_q(mul_prod);

// INTT output: convert from Montgomery form to standard form
// ntt_read_data is 27-bit signed -> 23-bit unsigned -> * R^{-1} -> 23-bit unsigned
assign out_mont   = from_signed_23($signed(ntt_read_data));
assign out_prod   = out_mont * 23'd4713473;
assign out_std    = mod_q(out_prod);

