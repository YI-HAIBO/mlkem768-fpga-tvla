/**
 * dilithium_ntt.v — Dilithium NTT-based polynomial multiplication
 * ================================================================
 * Wrapper around unified_ntt.v in SIGN mode (q=8380417, BW=27, 8 layers).
 *
 * Pipeline (mode=2):
 *   1. Load polynomial a into unified_ntt, run NTT
 *   2. Read a_ntt into external RAM
 *   3. Load polynomial b into unified_ntt, run NTT
 *   4. Read b_ntt into external RAM
 *   5. Compute basemul(a_ntt, b_ntt) = c_ntt, load into unified_ntt
 *   6. Run INTT on c_ntt
 *   7. Read result c
 *
 * mode=0: forward NTT only (load a, NTT, read a_ntt)
 * mode=1: inverse INTT only (load a, INTT, read result)
 * mode=2: full multiplication (NTT(a) + NTT(b) + basemul + INTT)
 *
 * Pointwise NTT-domain multiplication (verified against schoolbook):
 *   c[i] = a_ntt[i] * b_ntt[i] mod q   (standard multiplication, NOT fqmul)
 *   After INTT, multiply by R^{-1} to convert from Montgomery to standard form.
 */

module dilithium_ntt (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        start,
    output reg         busy,
    output reg         done,

    // Input polynomial interfaces (23-bit unsigned coefficients in [0, q-1])
    input  wire [7:0]  a_addr,
    input  wire [22:0] a_data,
    input  wire        a_wr,
    input  wire [7:0]  b_addr,
    input  wire [22:0] b_data,
    input  wire        b_wr,

    // Output
    output reg [7:0]  c_addr,
    output reg [22:0] c_data,

    // Mode: 0=NTT, 1=INTT, 2=multiplication
    input  wire [1:0]  mode,
    input  wire [22:0] omega_k   // unused, kept for interface compatibility
);

