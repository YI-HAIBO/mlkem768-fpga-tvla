// Main FSM
// =========================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state       <= S_ZETA_LOAD;
        idx         <= 8'd0;
        busy        <= 1'b0;
        done        <= 1'b0;
        c_addr      <= 8'd0;
        c_data      <= 23'd0;
        ntt_start   <= 1'b0;
        ntt_inverse <= 1'b0;
        ntt_load    <= 1'b0;
        ntt_load_addr <= 8'd0;
        ntt_load_data <= 27'd0;
        ntt_read_addr <= 8'd0;
        zeta_load   <= 1'b0;
        zeta_addr   <= 8'd0;
        zeta_data   <= 27'd0;
        mode_reg    <= 2'd0;
        read_substate <= 1'b0;
        ntt_start_pulsed <= 1'b0;
    end else begin
        done       <= 1'b0;
        ntt_start  <= 1'b0;
        ntt_load   <= 1'b0;
        zeta_load  <= 1'b0;

        case (state)

        // ------------------------------------------------------------
        // S_ZETA_LOAD: load 256 zeta entries into unified_ntt's ROM
        // ------------------------------------------------------------
        S_ZETA_LOAD: begin
            zeta_load <= 1'b1;
            zeta_addr <= idx;
            zeta_data <= get_zeta(idx);
            idx <= idx + 1'b1;
            if (idx == 8'd255) begin
                state <= S_IDLE;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_IDLE: wait for start
        // ------------------------------------------------------------
        S_IDLE: begin
            busy <= 1'b0;
            if (start) begin
                busy <= 1'b1;
                mode_reg <= mode;
                state <= S_BUF_LOAD_A;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_BUF_LOAD_A: nothing to do — buf_a already has data
        // This is a pass-through state for mode flexibility
        // ------------------------------------------------------------
        S_BUF_LOAD_A: begin
            state <= S_LOAD_A;
            idx <= 8'd0;
        end

        // ------------------------------------------------------------
        // S_LOAD_A: load buf_a into unified_ntt (sign-extended)
        // ------------------------------------------------------------
        S_LOAD_A: begin
            ntt_load <= 1'b1;
            ntt_load_addr <= idx;
            ntt_load_data <= {4'b0, buf_a[idx]};  // zero-extend (unified_ntt expects unsigned [0,q-1])
            idx <= idx + 1'b1;
            if (idx == 8'd255) begin
                state <= S_WAIT_NTT_A;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_WAIT_NTT_A: start forward NTT and wait
        // ------------------------------------------------------------
        S_WAIT_NTT_A: begin
            if (!ntt_start_pulsed) begin
                ntt_inverse <= 1'b0;
                ntt_start <= 1'b1;
                ntt_start_pulsed <= 1'b1;
            end else begin
                ntt_start <= 1'b0;
            end
            if (ntt_done) begin
                state <= S_READ_A;
                idx <= 8'd0;
                ntt_start_pulsed <= 1'b0;
            end
        end

        // ------------------------------------------------------------
        // S_READ_A: read NTT output, store in ram_a_ntt
        // ------------------------------------------------------------
        S_READ_A: begin
            if (read_substate == 1'b0) begin
                // Set read address for next cycle
                ntt_read_addr <= idx;
                read_substate <= 1'b1;
            end else begin
                // Capture data (ntt_read_addr was set last cycle)
                ram_a_ntt[idx] <= ntt_read_data;
                read_substate <= 1'b0;
                idx <= idx + 1'b1;
                if (idx == 8'd255) begin
                    case (mode_reg)
                        2'd0: state <= S_READ_OUT;
                        2'd2: state <= S_BUF_LOAD_B;
                        default: state <= S_DONE;
                    endcase
                end
            end
        end

        // ------------------------------------------------------------
        // S_BUF_LOAD_B: pass-through (buf_b already has data)
        // ------------------------------------------------------------
        S_BUF_LOAD_B: begin
            state <= S_LOAD_B;
            idx <= 8'd0;
        end

        // ------------------------------------------------------------
        // S_LOAD_B: load buf_b into unified_ntt
        // ------------------------------------------------------------
        S_LOAD_B: begin
            ntt_load <= 1'b1;
            ntt_load_addr <= idx;
            ntt_load_data <= {4'b0, buf_b[idx]};  // zero-extend (unified_ntt expects unsigned [0,q-1])
            idx <= idx + 1'b1;
            if (idx == 8'd255) begin
                state <= S_WAIT_NTT_B;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_WAIT_NTT_B: start forward NTT on b and wait
        // ------------------------------------------------------------
        S_WAIT_NTT_B: begin
            if (!ntt_start_pulsed) begin
                ntt_inverse <= 1'b0;
                ntt_start <= 1'b1;
                ntt_start_pulsed <= 1'b1;
            end else begin
                ntt_start <= 1'b0;
            end
            if (ntt_done) begin
                state <= S_READ_B;
                idx <= 8'd0;
                ntt_start_pulsed <= 1'b0;
            end
        end

        // ------------------------------------------------------------
        // S_READ_B: read NTT output, store in ram_b_ntt
        // ------------------------------------------------------------
        S_READ_B: begin
            if (read_substate == 1'b0) begin
                ntt_read_addr <= idx;
                read_substate <= 1'b1;
            end else begin
                ram_b_ntt[idx] <= ntt_read_data;
                read_substate <= 1'b0;
                idx <= idx + 1'b1;
                if (idx == 8'd255) begin
                    state <= S_PT_COMPUTE;
                    idx <= 8'd0;
                end
            end
        end

        // ------------------------------------------------------------
        // S_PT_COMPUTE: compute all 256 pointwise products into pt_buf
        //   c[idx] = a_ntt[idx] * b_ntt[idx] mod q  (standard multiplication)
        // ------------------------------------------------------------
        S_PT_COMPUTE: begin
            pt_buf[idx] <= mul_result;
            idx <= idx + 1'b1;
            if (idx == 8'd255) begin
                state <= S_PT_LOAD;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_PT_LOAD: load pt_buf into unified_ntt for INTT
        // ------------------------------------------------------------
        S_PT_LOAD: begin
            ntt_load <= 1'b1;
            ntt_load_addr <= idx;
            ntt_load_data <= {4'b0, pt_buf[idx]};  // zero-extend
            idx <= idx + 1'b1;
            if (idx == 8'd255) begin
                state <= S_WAIT_INTT;
                idx <= 8'd0;
            end
        end

        // ------------------------------------------------------------
        // S_WAIT_INTT: start inverse NTT and wait
        // ------------------------------------------------------------
        S_WAIT_INTT: begin
            if (!ntt_start_pulsed) begin
                ntt_inverse <= 1'b1;
                ntt_start <= 1'b1;
                ntt_start_pulsed <= 1'b1;
            end else begin
                ntt_start <= 1'b0;
            end
            if (ntt_done) begin
                state <= S_READ_OUT;
                idx <= 8'd0;
                ntt_start_pulsed <= 1'b0;
            end
        end

        // ------------------------------------------------------------
        // S_READ_OUT: read final result, output via c_addr/c_data
        // ------------------------------------------------------------
        S_READ_OUT: begin
            if (read_substate == 1'b0) begin
                ntt_read_addr <= idx;
                read_substate <= 1'b1;
            end else begin
                c_data  <= out_std;  // R^{-1} correction (Montgomery -> standard)
                c_addr  <= idx;
                read_substate <= 1'b0;
                idx <= idx + 1'b1;
                if (idx == 8'd255) begin
                    state <= S_DONE;
                end
            end
        end

        // ------------------------------------------------------------
        // S_DONE: pulse done, return to idle
        // ------------------------------------------------------------
        S_DONE: begin
            busy <= 1'b0;
            done <= 1'b1;
            state <= S_IDLE;
        end

        default: state <= S_IDLE;
        endcase
    end
end

endmodule
