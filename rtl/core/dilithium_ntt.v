// =========================================================================
// Unsigned [0, q-1] <-> Signed [-q/2, q/2-1] conversion functions
// =========================================================================

// Convert 23-bit unsigned [0, q-1] to 27-bit signed [-q/2, q/2-1]
function [26:0] to_signed_27;
    input [22:0] val;
    begin
        if (val < 23'd4190208)
            to_signed_27 = $signed({4'b0, val});
        else
            to_signed_27 = $signed({4'b0, val}) - 27'sd8380417;
    end
endfunction

// Convert 27-bit value to 23-bit unsigned [0, q-1] via signed mod-q reduction
// (matches TB's: ((($signed(v) % QD) + QD) % QD))
function [22:0] from_signed_23;
    input signed [26:0] val;
    reg signed [31:0] sv;
    reg signed [31:0] r;
    begin
        sv = $signed(val);
        r = sv % 32'sd8380417;
        if (r < 0) r = r + 32'sd8380417;
        from_signed_23 = r[22:0];
    end
endfunction

// =========================================================================
// Modular reduction: 46-bit unsigned product -> 23-bit unsigned [0, q-1]
// Uses Verilog's built-in modulo operator
// =========================================================================
function [22:0] mod_q;
    input [45:0] x;
    begin
        mod_q = x % 32'd8380417;
    end
endfunction

// =========================================================================
// Montgomery multiplication: fqmul(a, b) = a * b * R^-1 mod q
// Inputs/outputs: 23-bit unsigned [0, q-1] (Montgomery form)
// Two-step: temp = a*b mod q, result = temp*R^{-1} mod q
// =========================================================================
function [22:0] fqmul_func;
    input [22:0] a;
    input [22:0] b;
    reg [45:0] prod;
    reg [22:0] temp;
    reg [45:0] prod2;
    begin
        prod = a * b;
        temp = mod_q(prod);
        prod2 = temp * 23'd4713473;
        fqmul_func = mod_q(prod2);
    end
endfunction

