#!/usr/bin/env python3
"""
Single-module Vivado timing probe.

Usage:
    python scripts/synth_one.py kyber_ntt            # baseline run
    python scripts/synth_one.py kyber_ntt -tag p1    # tagged run (keeps reports apart)
    python scripts/synth_one.py kyber_ntt -clk 10.0  # override clock period (ns)

Copies the module's .v into an ASCII-only temp dir (Vivado chokes on the
Chinese workspace path), synthesises it standalone against constrains/kem.xdc,
and prints WNS / Fmax / utilization.  Reports are copied to
results/synth_one_<mod><tag>_*.rpt
"""
import subprocess, os, sys, shutil, time, io, re

WORKSPACE = r"C:\Users\Yi\WorkBuddy\2026-10-05-09-29-14"
PROJECT   = os.path.join(WORKSPACE, "调研FPGA大模型安全", "研发", "ipx_aoi_fpga_prototype")
CORE      = os.path.join(PROJECT, "rtl", "core")
CONST     = os.path.join(PROJECT, "constrains")
RESULTS   = os.path.join(PROJECT, "results")

VIVADO = r"D:\FPGA\2026.1\Vivado\bin\vivado.bat"
PART   = "xc7a100tcsg324-1"
TIMEOUT = 600


def main():
    args = [a for a in sys.argv[1:]]
    if not args:
        print(__doc__)
        return 2
    mod = args[0]
    tag = ""
    period = 10.0
    if "-tag" in args:
        tag = "_" + args[args.index("-tag") + 1]
    if "-clk" in args:
        period = float(args[args.index("-clk") + 1])

    src = os.path.join(CORE, mod + ".v")
    if not os.path.exists(src):
        print("no such source:", src)
        return 2

    stamp = str(int(time.time()))
    TMP      = "C:/tmp_one_%s%s_%s" % (mod, tag.replace("_", "-"), stamp)
    TMP_CORE = os.path.join(TMP, "core")
    TMP_XDC  = os.path.join(TMP, "one.xdc")
    TMP_TCL  = os.path.join(TMP, "synth.tcl")
    TMP_LOG  = os.path.join(TMP, "synth.log")
    TMP_PROJ = os.path.join(TMP, "proj")
    os.makedirs(TMP_CORE, exist_ok=True)
    shutil.copy2(src, os.path.join(TMP_CORE, mod + ".v"))

    # NOTE: constrains/kem.xdc has two defects that make it a no-op / an error
    # on Vivado 2026.1, so a clean constraint set is generated here instead:
    #   * `set_input_jitter 0.1 [get_clocks ...]` has the arguments the wrong
    #     way round (jitter first) -> "clock '0.1' not found", silently dropped;
    #   * it constrains ports other than clk/rst_n that a standalone module
    #     does not have.
    xdc = (
        "# standalone single-module timing probe, generated by scripts/synth_one.py\n"
        "create_clock -period %s [get_ports clk]\n"
        "set_clock_uncertainty 0.2 [get_clocks -of_objects [get_ports clk]]\n"
        "set_input_jitter [get_clocks -of_objects [get_ports clk]] 0.1\n"
        "set_false_path -from [get_ports rst_n]\n"
    ) % period
    with io.open(TMP_XDC, "w", encoding="utf-8") as fh:
        fh.write(xdc)

    tcl = """set PROJ "%s"
set CORE "$PROJ/core"
set XDC  "$PROJ/one.xdc"
set PART "%s"
puts "=== Synth %s @ %s ns ==="
set WORK "$PROJ/proj"
if {[file exists $WORK]} { file delete -force $WORK }
file mkdir $WORK
create_project -force one_synth $WORK -part $PART
add_files "$CORE/%s.v"
read_xdc $XDC
synth_design -top %s -part $PART -directive RuntimeOptimized
set RPT "$WORK/reports"
file mkdir $RPT
report_utilization -file "$RPT/util.rpt"
report_timing_summary -file "$RPT/timing.rpt" -delay_type min_max -max_paths 5
report_timing -file "$RPT/path.rpt" -delay_type max -max_paths 5 -input_pins -sort_by group
puts "=== Done ==="
exit
""" % (TMP, PART, mod, period, mod, mod)

    with io.open(TMP_TCL, "w", encoding="utf-8") as fh:
        fh.write(tcl)

    cmd = [VIVADO, "-mode", "batch", "-nojournal", "-log", TMP_LOG, "-source", TMP_TCL]
    t0 = time.time()
    print("CMD: %s" % " ".join(cmd))
    try:
        r = subprocess.run(cmd, capture_output=True, text=True,
                           timeout=TIMEOUT, cwd=TMP, errors="replace")
        el = time.time() - t0
        print("rc=%d  time=%.1fs" % (r.returncode, el))
    except subprocess.TimeoutExpired:
        print("TIMEOUT after %.1fs" % (time.time() - t0))
        return -1

    rpt_dir = os.path.join(TMP_PROJ, "reports")
    prefix = "synth_one_%s%s" % (mod, tag)
    if os.path.exists(rpt_dir):
        for rf in ("util.rpt", "timing.rpt", "path.rpt"):
            p = os.path.join(rpt_dir, rf)
            if os.path.exists(p):
                shutil.copy2(p, os.path.join(RESULTS, prefix + "_" + rf))

    tp = os.path.join(rpt_dir, "timing.rpt")
    if os.path.exists(tp):
        with io.open(tp, "r", encoding="utf-8", errors="replace") as fh:
            txt = fh.read()
        m = re.search(r"WNS\(ns\)\s+TNS\(ns\).*?\n\s*(-\d+\.\d+|\d+\.\d+)\s+", txt)
        if not m:
            m = re.search(r"WNS\s*=?\s*(-?\d+\.\d+)", txt)
        if m:
            wns = float(m.group(1))
            fmax = 1000.0 / (period - wns) if (period - wns) > 0 else 0.0
            print("WNS = %+.3f ns   -> Fmax = %.1f MHz" % (wns, fmax))
        for line in txt.splitlines():
            if "Slack" in line and ":" in line and "ns" in line:
                print("   ", line.strip())

    up = os.path.join(rpt_dir, "util.rpt")
    if os.path.exists(up):
        with io.open(up, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                s = line.strip()
                if re.match(r"^(Slice LUTs|Slice Registers|DSPs|Block RAM Tile|F7 Muxes|F8 Muxes|LUT as Logic|LUT as Memory)\b", s):
                    print("  ", s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
