#!/usr/bin/env python3
"""
Parameterised Vivado timing probe for rtl/core/unified_ntt.v (innovation A1).

The DUT is parameterised, so each mode needs a thin wrapper module that bakes
the parameters in and exposes every DUT port at the top level (exposing, not
tying off, so Vivado cannot constant-propagate the datapath away).

One Vivado process per mode: create_project -> synth_design -> report_* ->
write_checkpoint.  The checkpoint is deliberately LAST: on this machine it has
been observed to stall for minutes with zero I/O (see the notes below), and
it must not be allowed to block the reports it is only there to preserve.
Every TCL step also drops a marker file, so a stuck step is identified by name.

Two Windows/Tcl landmines this driver was written around:
  * Tcl double-quoted strings process backslash escapes (`\t` == TAB), so every
    path substituted into the TCL must be forward-slashed.
  * Vivado's stdout must NOT go through a pipe that is drained only at exit --
    it fills the ~64 KB buffer and blocks, and its `-log` mirror stops with it
    (observed: elapsed 09:46 against cpu 00:00:12, i.e. 2% utilisation).

Usage:
    python scripts/synth_unified_ntt.py sign          # Dilithium mode only
    python scripts/synth_unified_ntt.py kem           # Kyber mode only
    python scripts/synth_unified_ntt.py both          # both, KEM then SIGN
    python scripts/synth_unified_ntt.py sign -clk 10.0 -tag v1
    python scripts/synth_unified_ntt.py sign -dir RuntimeOptimized

Reports land in results/synth_unified_ntt_<mode><tag>_{util,timing,path}.rpt
Run with `python -u` for live progress.
"""
