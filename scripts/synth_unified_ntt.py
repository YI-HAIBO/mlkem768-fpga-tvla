def wrapper_src(wrap, p):
    """Generate the ASCII-only wrapper: all DUT ports mirrored at top level."""
    bw = p["BW"]
    na = p["N_LAYERS"]                       # zeta_addr width
    l = lambda w: ("[%d:0]" % (w - 1)) if w > 1 else ""
    f = {"p_" + k: p[k] for k in PORT_ORDER}
    return """\
`timescale 1ns / 1ps
`default_nettype none

// Auto-generated by scripts/synth_unified_ntt.py -- do not edit by hand.
// Top-level wrapper for {dut} in MODE={wrap}.
// Every DUT port is mirrored so synthesis keeps the full datapath.

module {wrap}(
    input  wire            clk,
    input  wire            rst_n,
    input  wire            start,
    input  wire            inverse,
    output wire            busy,
    output wire            done,
    input  wire            load,
    input  wire [7:0]      load_addr,
    input  wire {bw}       load_data,
    input  wire [7:0]      read_addr,
    output wire {bw}       read_data,
    input  wire            zeta_load,
    input  wire {na}       zeta_addr,
    input  wire {bw}       zeta_data
);

    {dut} #(
        .N           ({p_N}),
        .N_LAYERS    ({p_N_LAYERS}),
        .BW          ({p_BW}),
        .Q           ({p_Q}),
        .QINV        ({p_QINV}),
        .R_MOD       ({p_R_MOD}),
        .SCALE_K     ({p_SCALE_K}),
        .BARRETT_M   ({p_BARRETT_M}),
        .BARRETT_SH  ({p_BARRETT_SH})
    ) u_ntt (
        .clk        (clk),
        .rst_n      (rst_n),
        .start      (start),
        .inverse    (inverse),
        .busy       (busy),
        .done       (done),
        .load       (load),
        .load_addr  (load_addr),
        .load_data  (load_data),
        .read_addr  (read_addr),
        .read_data  (read_data),
        .zeta_load  (zeta_load),
        .zeta_addr  (zeta_addr),
        .zeta_data  (zeta_data)
    );

endmodule
`default_nettype wire
""".format(dut=DUT, wrap=wrap, bw=l(bw), na=l(na), **f)


