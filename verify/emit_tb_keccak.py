"""emit_tb_keccak.py — generate a correct, self-checking testbench for the
2-way pipelined keccak_perm and the shake sponge (SHAKE-128 and SHAKE-256).

All golden vectors come from gen_rc_vectors.py's LFSR-based, hashlib-verified
model.  This removes the hand-copy typos that broke the previous
tb_keccak_pipeline.v (which pulled vectors from the buggy keccak_ref.py).

Emits verify/tb_keccak_pipeline.v with:
  * keccak_perm regression: zero-input and single-bit (lane0.bit0) Keccak-f
  * shake sponge regression: SHAKE128/256 of "" and "abc" (KAT vs hashlib)
  * a watchdog so a stuck FSM cannot hang the run forever.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_rc_vectors import permute, shake128, shake256  # noqa


def perm_state_hex(lanes):
    """1600-bit MSB-first hex (lane24..lane0) for a [1599:0] literal."""
    return "".join("%016x" % lanes[gi] for gi in range(24, -1, -1))


def emit():
    zero = permute([0] * 25)
    single = permute([1] + [0] * 24)

    shake_cases = [
        (0, "SHAKE128", "empty", b"", 32, shake128),
        (0, "SHAKE128", "abc", b"abc", 32, shake128),
        (1, "SHAKE256", "empty", b"", 32, shake256),
        (1, "SHAKE256", "abc", b"abc", 64, shake256),
    ]

    L = []
    L.append("// Auto-generated by emit_tb_keccak.py — DO NOT hand-edit.")
    L.append("// Golden vectors: LFSR RC, hashlib-verified.")
    L.append("`timescale 1ns / 1ps")
    L.append("`default_nettype none")
    L.append("module tb_keccak_pipeline;")
    L.append("    localparam MAX_IN = 256;")
    L.append("    localparam MAX_OUT = 512;")
    L.append("    reg clk = 0;")
    L.append("    always #5 clk = ~clk;")
    L.append("    reg rst_n = 0;")
    L.append("    // ---- watchdog ----")
    L.append("    reg watchdog_hit = 0;")
    L.append("    initial #400000 if (!watchdog_hit) begin")
    L.append('        $display("WATCHDOG: test timed out (stuck FSM?)");')
    L.append("        $finish;")
    L.append("    end")
    L.append("")
    L.append("    // ============ keccak_perm DUT ============")
    L.append("    reg start_k = 0;")
    L.append("    reg [1599:0] state_in = 1600'd0;")
    L.append("    wire [1599:0] state_out;")
    L.append("    wire done_k;")
    L.append("    keccak_perm #(.WIDTH(1600)) u_k (")
    L.append("        .clk(clk), .rst_n(rst_n), .start(start_k),")
    L.append("        .state_in(state_in), .state_out(state_out), .done(done_k));")
    L.append("")
    L.append("    // ============ shake DUTs (separate done + rd channels) ============")
    L.append("    reg start_s = 0;")
    L.append("    reg [15:0] msg_len = 0;")
    L.append("    reg [15:0] out_len = 0;")
    L.append("    reg wr_en = 0;")
    L.append("    reg [15:0] wr_addr = 0;")
    L.append("    reg [7:0] wr_data = 0;")
    L.append("    reg [15:0] rd_addr = 0;")
    L.append("    wire [7:0] rd_data128, rd_data256;")
    L.append("    wire done128, done256;")
    L.append("    shake #(.RATE(168), .MAX_IN(MAX_IN), .MAX_OUT(MAX_OUT)) u_s128 (")
    L.append("        .clk(clk), .rst_n(rst_n), .start(start_s),")
    L.append("        .msg_len(msg_len), .out_len(out_len),")
    L.append("        .wr_en(wr_en), .wr_addr(wr_addr), .wr_data(wr_data),")
    L.append("        .rd_addr(rd_addr), .rd_data(rd_data128),")
    L.append("        .busy(), .done(done128));")
    L.append("    shake #(.RATE(136), .MAX_IN(MAX_IN), .MAX_OUT(MAX_OUT)) u_s256 (")
    L.append("        .clk(clk), .rst_n(rst_n), .start(start_s),")
    L.append("        .msg_len(msg_len), .out_len(out_len),")
    L.append("        .wr_en(wr_en), .wr_addr(wr_addr), .wr_data(wr_data),")
    L.append("        .rd_addr(rd_addr), .rd_data(rd_data256),")
    L.append("        .busy(), .done(done256));")
    L.append("")
    L.append("    task reset_sys;")
    L.append("        begin")
    L.append("            rst_n = 0; start_k = 0; start_s = 0;")
    L.append("            repeat (4) @(posedge clk);")
    L.append("            rst_n = 1;")
    L.append("            repeat (2) @(posedge clk);")
    L.append("        end")
    L.append("    endtask")
    L.append("")
    L.append("    // ---------- keccak_perm check ----------")
    L.append("    task check_perm;")
    L.append("        input [1599:0] din;")
    L.append("        input [1599:0] dexpected;")
    L.append("        input [127:0] tag;")
    L.append("        begin")
    L.append("            state_in = din;")
    L.append("            start_k = 1; @(posedge clk);")
    L.append("            @(negedge clk); start_k = 0;")
    L.append("            wait (done_k); @(posedge clk);")
    L.append("            if (state_out !== dexpected) begin")
    L.append('                $display("FAIL perm %s", tag);')
    L.append('                $display("  got: %h", state_out);')
    L.append('                $display("  exp: %h", dexpected);')
    L.append("                $finish;")
    L.append("            end")
    L.append('            $display("PASS perm %s", tag);')
    L.append("        end")
    L.append("    endtask")
    L.append("")
    L.append("    // ---------- shake check (which: 0=SHAKE128, 1=SHAKE256) ----------")
    L.append("    task check_shake;")
    L.append("        input [15:0] mlen;")
    L.append("        input [15:0] olen;")
    L.append("        input which;")
    L.append("        input [127:0] tag;")
    L.append("        integer i;")
    L.append("        begin")
    L.append("            wr_en = 0;")
    L.append("            for (i = 0; i < mlen; i = i + 1) begin")
    L.append("                wr_addr = i[15:0];")
    L.append("                wr_data = mbuf[i];")
    L.append("                wr_en = 1; @(posedge clk);")
    L.append("            end")
    L.append("            wr_en = 0;")
    L.append("            msg_len = mlen; out_len = olen;")
    L.append("            start_s = 1; @(posedge clk);")
    L.append("            @(negedge clk); start_s = 0;")
    L.append("            if (which == 0) wait (done128);")
    L.append("            else            wait (done256);")
    L.append("            @(posedge clk);")
    L.append("            for (i = 0; i < olen; i = i + 1) begin")
    L.append("                rd_addr = i[15:0]; @(posedge clk);")
    L.append("                if (which == 0) begin")
    L.append("                    if (rd_data128 !== expbuf[i]) begin")
    L.append('                        $display("FAIL shake %s byte %0d: got %h exp %h",')
    L.append("                                 tag, i, rd_data128, expbuf[i]);")
    L.append("                        $finish;")
    L.append("                    end")
    L.append("                end else begin")
    L.append("                    if (rd_data256 !== expbuf[i]) begin")
    L.append('                        $display("FAIL shake %s byte %0d: got %h exp %h",')
    L.append("                                 tag, i, rd_data256, expbuf[i]);")
    L.append("                        $finish;")
    L.append("                    end")
    L.append("                end")
    L.append("            end")
    L.append('            $display("PASS shake %s", tag);')
    L.append("        end")
    L.append("    endtask")
    L.append("")
    L.append("    reg [7:0] mbuf   [0:255];")
    L.append("    reg [7:0] expbuf [0:255];")
    L.append("    // ---------- golden states ----------")
    L.append("    localparam [1599:0] EXP_ZERO  = 1600'h%s;" % perm_state_hex(zero))
    L.append("    localparam [1599:0] EXP_BIT0  = 1600'h%s;" % perm_state_hex(single))
    L.append("")
    L.append("    initial begin")
    L.append('        $dumpfile("keccak_pipeline.vcd");')
    L.append('        $dumpvars(0, tb_keccak_pipeline);')
    L.append("        watchdog_hit = 0;")
    L.append("        reset_sys;")
    L.append("")
    L.append("        check_perm(1600'd0, EXP_ZERO, \"zero\");")
    L.append("        reset_sys;")
    L.append("        check_perm(1600'h0000000000000001, EXP_BIT0, \"bit0\");")
    L.append("")
    for idx, (which, name, lit, msg, n, fn) in enumerate(shake_cases):
        gold = fn(msg, n)
        tag = "%s_%s" % (name, lit)
        L.append("        // --- shake: %s ---" % tag)
        L.append("        begin : load_%d" % idx)
        for i, b in enumerate(msg):
            L.append("            mbuf[%2d] = 8'h%02x;" % (i, b))
        for i, b in enumerate(gold):
            L.append("            expbuf[%2d] = 8'h%02x;" % (i, b))
        L.append("        end")
        L.append("        reset_sys;")
        L.append('        check_shake(%2d, %2d, %d, "%s");' % (len(msg), n, which, tag))
    L.append("")
    L.append("        watchdog_hit = 1;")
    L.append('        $display("All keccak/shake regression tests passed.");')
    L.append("        $finish;")
    L.append("    end")
    L.append("endmodule")
    L.append("`default_nettype wire")
    L.append("")

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tb_keccak_pipeline.v")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote", path, "(", len("\n".join(L)), "bytes )")


if __name__ == "__main__":
    emit()
