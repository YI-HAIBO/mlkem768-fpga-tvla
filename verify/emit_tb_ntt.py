#!/usr/bin/env python3
"""emit_tb_ntt.py -- generate verify/tb_kyber_ntt.v + verify/ntt_golden.mem.

Why this exists
---------------
kyber_ntt.v had been validated only through Python oracles (ring
homomorphism, zeta identity, round trip).  None of that exercises the RTL:
a bug in the coefficient indexing, the state encoding, the write-back
ordering or the FSM would sail through undetected.  This testbench closes
that gap by driving the real module in iverilog against the golden vectors
emitted by verify/gen_ntt_vectors.py.

Golden vectors live in one flat hex file (one 16-bit value per line,
5120 lines = 20 vectors x 256 coefficients) loaded with `$readmemh`.
This dodges three separate iverilog limitations, each of which I hit and
confirmed with a minimal probe:

  1. multi-line `define macros whose expansion is a concatenation are a
     syntax error;
  2. comma-joined assignments into an unpacked array (`GOLD[0]=.., GOLD[1]=..`)
     are a syntax error (line 13 of the probe);
  3. task/subroutine ports may not carry unpacked dimensions.

So: one flat memory, module-level, tasks take a base *index* instead of
an array.

Vector semantics (from gen_ntt_vectors.build_vectors):
  X_t    = the raw test polynomial
  NTT_t  = ntt(X_t)          -- forward target
  INTT_t = invntt(X_t)       -- inverse of the RAW polynomial
  RT_t   = invntt(ntt(X_t))  -- inverse of the forward result (= 2285 * X_t)

The inverse tests therefore come in two families:
  load X_t   -> expect INTT_t   (inverse on raw input)
  load NTT_t -> expect RT_t     (the transform-domain round trip)
Loading NTT_t and expecting INTT_t is WRONG -- INTT_t is invntt(X_t), not
invntt(NTT_t); that mismatch made every inverse test report 256/256
differences even though the DUT was bit-exact.

iverilog traps elsewhere in this bench:
  * start is pulsed from negedge (a posedge-time pulse races the DUT's own
    posedge sample in iverilog's nondeterministic scheduling order).
  * the same race hits ANY DUT input driven with blocking assignments in a
    loop whose `@(posedge clk)` immediately follows: the assignment can land
    in the identical time step as the edge it precedes, and iverilog may
    schedule the bench's continuation ahead of the DUT's always block, so the
    DUT samples the NEXT iteration's input value (this cost coeff[0] on every
    load that followed a read-back phase: test 0 passed, tests 1-9 failed).
    Fix: drive load/load_addr/load_data (and read_addr) off negedge clk.
  * done is waited for with `wait (done)` then one settling clock, so a
    one-cycle done pulse cannot be missed.
"""
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
RESULTS = os.path.join(PROJECT, "results")
N = 256


def load_golden():
    with io.open(os.path.join(RESULTS, "ntt_golden.json"), encoding="utf-8") as f:
        return json.load(f)


def main():
    g = load_golden()
    vecs = g["vectors"]
    r_mod_q = g["r_mod_q"]

    tags = ("RAND", "ZERO", "POS", "NEG", "EXT")
    kinds = ("X", "NTT", "INTT", "RT")

    # ---- flat hex dump ------------------------------------------------------
    mem = []
    index = {}
    for kind in kinds:
        for tag in tags:
            key = "%s_%s" % (kind, tag)
            index[key] = len(mem)
            mem.extend("%04X" % (v & 0xFFFF) for v in vecs[key])

    mem_dest = os.path.join(HERE, "ntt_golden.mem")
    with io.open(mem_dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(mem) + "\n")
    print("wrote %s (%d lines)" % (mem_dest, len(mem)))

    # ---- testbench ----------------------------------------------------------
    L = []
    A = L.append
    nvec = len(index)

    A("// =============================================================================")
    A("// Auto-generated by verify/emit_tb_ntt.py -- do not edit by hand.")
    A("// Testbench for rtl/core/kyber_ntt.v against the golden vectors in")
    A("// verify/ntt_golden.mem (produced from results/ntt_golden.json, whose")
    A("// model is cross-checked by the ring-homomorphism oracle).")
    A("//")
    A("// Run from the project root:")
    A("//   iverilog -g2012 -o tb.vvp verify/tb_kyber_ntt.v rtl/core/kyber_ntt.v")
    A("//   vvp tb.vvp")
    A("// ($readmemh resolves the path relative to the invocation directory;")
    A("//  the bench therefore references verify/ntt_golden.mem directly.)")
    A("// =============================================================================")
    A("")
    A("`timescale 1ns / 1ps")
    A("")
    A("module tb_kyber_ntt;")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // golden vectors: flat %d-entry memory, one 16-bit coeff per entry." % (nvec * N))
    A("    // Layout: [X_*, NTT_*, INTT_*] in tag order RAND,ZERO,POS,NEG,EXT.")
    A("    // ----------------------------------------------------------------")
    A("    reg [15:0] GOLD [0:%d];" % (nvec * N - 1))
    for kind in kinds:
        offsets = [index["%s_%s" % (kind, tag)] for tag in tags]
        A("    localparam integer %-10s = %4d;  // %s"
          % ((kind + "_BASE").ljust(10), offsets[0],
             ", ".join("%d" % o for o in offsets[1:])))
    A("")
    A("    initial $readmemh(\"verify/ntt_golden.mem\", GOLD);")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // clock / reset")
    A("    // ----------------------------------------------------------------")
    A("    reg clk = 0;")
    A("    reg rst_n = 0;")
    A("")
    A("    always #5 clk = ~clk;")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // DUT signals")
    A("    // ----------------------------------------------------------------")
    A("    reg                start = 0;")
    A("    reg                inverse = 0;")
    A("    wire               busy;")
    A("    wire               done;")
    A("")
    A("    reg                load = 0;")
    A("    reg  [7:0]         load_addr = 0;")
    A("    reg  [15:0]        load_data = 0;")
    A("")
    A("    reg  [7:0]         read_addr = 0;")
    A("    wire [15:0]        read_data;")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // DUT")
    A("    // ----------------------------------------------------------------")
    A("    kyber_ntt #(.N(256), .Q(3329), .BW(16)) dut (")
    A("        .clk        (clk),")
    A("        .rst_n      (rst_n),")
    A("        .start      (start),")
    A("        .inverse    (inverse),")
    A("        .busy       (busy),")
    A("        .done       (done),")
    A("        .load       (load),")
    A("        .load_addr  (load_addr),")
    A("        .load_data  (load_data),")
    A("        .read_addr  (read_addr),")
    A("        .read_data  (read_data)")
    A("    );")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // watchdog -- generous: 15 tests x (256 load + ~4000 pipelined")
    A("    // transform ticks + 256 read).  The 3-tick butterfly pipeline is")
    A("    // ~3x slower than the original single-cycle DUT, so this must")
    A("    // cover ~60k cycles = 600 us; 5 ms leaves ample headroom.")
    A("    // ----------------------------------------------------------------")
    A("    initial begin")
    A("        #5000000;")
    A("        $display(\"FATAL: watchdog fired at %t\", $time);")
    A("        $finish;")
    A("    end")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // counters and shared state")
    A("    // ----------------------------------------------------------------")
    A("    integer n_pass = 0;")
    A("    integer n_fail = 0;")
    A("    integer i;")
    A("    integer nbad;")
    A("    integer first;")
    A("    reg [15:0] R;")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // helpers")
    A("    // ----------------------------------------------------------------")
    A("    task reset_dut;")
    A("        begin")
    A("            start = 0; load = 0; inverse = 0;")
    A("            load_addr = 0; load_data = 0; read_addr = 0;")
    A("            rst_n = 0;")
    A("            repeat (4) @(posedge clk);")
    A("            rst_n = 1;")
    A("            @(posedge clk);")
    A("        end")
    A("    endtask")
    A("")
    A("    // Stream 256 coefficients in, coeff 0 first.")
    A("    //")
    A("    // RACE-FIX (the 1-pass/9-fail bug): load/load_addr/load_data MUST be")
    A("    // driven off negedge clk.  When they were plain blocking assignments")
    A("    // in a loop that then did `@(posedge clk)`, the first iteration's")
    A("    // assignments could land in the SAME simulation-time step as the very")
    A("    // posedge they were meant to precede.  iverilog then sometimes ran the")
    A("    // bench's continuation (already setting iteration i+1's load_addr)")
    A("    // BEFORE the DUT's always block sampled its inputs at that posedge --")
    A("    // so the DUT wrote coeff[1] when the bench meant coeff[0], silently")
    A("    // losing exactly one coefficient per load phase.  The loss only bit")
    A("    // when the load was preceded by a #1-terminated read-back phase")
    A("    // (check_result), which is why test 0 (fresh from reset) passed and")
    A("    // tests 1-9 failed.  With every input changing at negedge and the")
    A("    // write happening at the following posedge, there is a 5 ns setup")
    A("    // margin and no scheduling-order dependency can exist.")
    A("    task load_vec;")
    A("        input integer base;")
    A("        begin")
    A("            @(negedge clk);")
    A("            load = 1;")
    A("            for (i = 0; i < 256; i = i + 1) begin")
    A("                load_addr = i[7:0];")
    A("                load_data = GOLD[base + i];")
    A("                @(posedge clk);      // DUT samples addr=i, data=GOLD[base+i]")
    A("                @(negedge clk);      // safe point for the next address")
    A("            end")
    A("            load = 0;")
    A("        end")
    A("    endtask")
    A("")
    A("    // Pulse start for exactly one sampled clock, driven off negedge so")
    A("    // the DUT cannot miss it through a posedge-time race.")
    A("    task pulse_start;")
    A("        begin")
    A("            @(negedge clk);")
    A("            start = 1;")
    A("            @(posedge clk);")
    A("            @(negedge clk);")
    A("            start = 0;")
    A("        end")
    A("    endtask")
    A("")
    A("    task wait_done;")
    A("        begin")
    A("            wait (done === 1'b1);")
    A("            @(posedge clk);")
    A("        end")
    A("    endtask")
    A("")
    A("    // Read the result back coefficient by coefficient and compare")
    A("    // against the golden half of the same pair.  read_addr is driven off")
    A("    // negedge so the combinational read port has a full half-cycle to")
    A("    // settle before the sample; #1 is kept as a delta-settle guard.")
    A("    task check_result;")
    A("        input integer exp_base;")
    A("        begin")
    A("            nbad  = 0;")
    A("            first = -1;")
    A("            @(negedge clk);")
    A("            for (i = 0; i < 256; i = i + 1) begin")
    A("                read_addr = i[7:0];")
    A("                #1;")
    A("                R = read_data;")
    A("                if (R !== GOLD[exp_base + i]) begin")
    A("                    nbad = nbad + 1;")
    A("                    if (first < 0) first = i;")
    A("                end")
    A("            end")
    A("        end")
    A("    endtask")
    A("")
    A("    task run_fwd;")
    A("        input integer in_base;")
    A("        input integer exp_base;")
    A("        input integer tnum;")
    A("        begin")
    A("            inverse = 1'b0;")
    A("            load_vec(in_base);")
    A("            pulse_start;")
    A("            wait_done;")
    A("            check_result(exp_base);")
    A("            if (nbad == 0) begin")
    A("                n_pass = n_pass + 1;")
    A("                $display(\"PASS  forward NTT  test %0d\", tnum);")
    A("            end else begin")
    A("                n_fail = n_fail + 1;")
    A("                $display(\"FAIL  forward NTT  test %0d : %0d/256 differ, first %0d\",")
    A("                         tnum, nbad, first);")
    A("            end")
    A("        end")
    A("    endtask")
    A("")
    A("    task run_inv;")
    A("        input integer in_base;")
    A("        input integer exp_base;")
    A("        input integer tnum;")
    A("        begin")
    A("            inverse = 1'b1;")
    A("            load_vec(in_base);")
    A("            pulse_start;")
    A("            wait_done;")
    A("            check_result(exp_base);")
    A("            if (nbad == 0) begin")
    A("                n_pass = n_pass + 1;")
    A("                $display(\"PASS  inverse INTT test %0d\", tnum);")
    A("            end else begin")
    A("                n_fail = n_fail + 1;")
    A("                $display(\"FAIL  inverse INTT test %0d : %0d/256 differ, first %0d\",")
    A("                         tnum, nbad, first);")
    A("            end")
    A("        end")
    A("    endtask")
    A("")
    A("    // ----------------------------------------------------------------")
    A("    // main")
    A("    // ----------------------------------------------------------------")
    A("    initial begin")
    A("        $dumpfile(\"tb_kyber_ntt.vcd\");")
    A("        $dumpvars(0, tb_kyber_ntt);")
    A("")
    A("        reset_dut;")
    A("        $display(\"--- kyber_ntt KAT: q=3329, N=256, R mod q=%0d ---\","
      " %0d);" % (r_mod_q, r_mod_q))
    A("")
    tnum = 0
    for tag in tags:
        A("        // X_%s -> NTT_%s" % (tag, tag))
        A("        run_fwd(X_BASE + %d, NTT_BASE + %d, %d);"
          % (256 * tnum, 256 * tnum, tnum))
        tnum += 1
    A("")
    for tag in tags:
        A("        // X_%s -> INTT_%s  (inverse on the raw polynomial)"
          % (tag, tag))
        A("        run_inv(X_BASE + %d, INTT_BASE + %d, %d);"
          % (256 * (tnum - 5), 256 * (tnum - 5), tnum))
        tnum += 1
    A("")
    for tag in tags:
        A("        // NTT_%s -> RT_%s  (round trip: invntt of ntt(x) = 2285*x)"
          % (tag, tag))
        A("        run_inv(NTT_BASE + %d, RT_BASE + %d, %d);"
          % (256 * (tnum - 10), 256 * (tnum - 10), tnum))
        tnum += 1
    A("")
    A("        $display(\"---------------------------------------------\");")
    A("        $display(\"RESULT: %0d passed, %0d failed\", n_pass, n_fail);")
    A("        if (n_fail == 0)")
    A("            $display(\"ALL TESTS PASSED\");")
    A("        else")
    A("            $display(\"TESTS FAILED\");")
    A("        $finish;")
    A("    end")
    A("")
    A("endmodule")
    A("")

    out = "\n".join(L)
    dest = os.path.join(HERE, "tb_kyber_ntt.v")
    with io.open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote %s (%d bytes)" % (dest, os.path.getsize(dest)))
    return 0


if __name__ == "__main__":
    sys.exit(main())