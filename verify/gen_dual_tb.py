#!/usr/bin/env python3
"""Generate sim/tb_unified_ntt_dual.v -- runtime KEM<->SIGN switching TB.

Single unified_ntt instance fixed to the widest datapath (BW=27, N_LAYERS=8,
SIGN compile-time defaults).  The cfg_* port pair reprograms the runtime
constant registers; the zeta ROM is reloaded between phases:

  Phase A: KEM@2^27 radix  (Q=3329, QINV=61403905, SCALE_K=2811, M=20159,
           SH=26, NL=7, zeta27 table) -> forward range / round-trip /
           INTT(0) / non-trivial vector; round-trip output saved.
  Phase B: SIGN (Q=8380417, QINV=58728449, SCALE_K=49145, M=33587228,
           SH=48, NL=8, sign zeta table) -> forward bit-exact vs the gold
           vectors of tb_unified_ntt_sign.v + round-trip + range.
  Phase C: switch back to KEM, re-run the Phase-A round-trip, outputs must
           match Phase A bit-for-bit.

Constants come from verify/kem27_model.py (validated there before codegen).
Tables (zeta27, sign zeta, sign f1, sign gold_ntt) are parsed from the
existing trusted testbenches so there is a single source of truth.

Usage: python verify/gen_dual_tb.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kem27_model as km

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
TB_PATH = os.path.join(ROOT, "sim", "tb_unified_ntt_dual.v")
BW = 27
MASK = (1 << BW) - 1


def vlit(v):
    """Canonical signed value -> 27-bit unsigned literal."""
    return "%d'd%d" % (BW, v & MASK)


def table_decl(name, vals, depth):
    lines = []
    lines.append("    reg [%d-1:0] %s [0:%d];" % (BW, name, depth - 1))
    lines.append("    initial begin")
    for i, v in enumerate(vals):
        lines.append("        %s[%d] = %s;" % (name, i, vlit(v)))
    lines.append("    end")
    return "\n".join(lines)


def main():
    kem_zeta16, sign_zeta, f1, gold_ntt = km.load_tables()
    k27, zeta27 = km.kem27_constants(kem_zeta16)

    # sanity: the model must validate before we generate any RTL TB
    ok, _, _ = km.validate()
    if not ok:
        print("kem27 model validation FAILED -- refusing to generate TB")
        sys.exit(1)

    # test polynomials (unsigned [0,q) representations)
    rng = [0] * 256
    s = 20261024
    for i in range(256):
        s = (1103515245 * s + 12345) % (1 << 31)
        rng[i] = s % 3329
    rng27 = [0] * 256
    s = 7630117
    for i in range(256):
        s = (1103515245 * s + 12345) % (1 << 31)
        rng27[i] = s % 8380417

    src = """\
`timescale 1ns / 1ps
// =============================================================================
// tb_unified_ntt_dual.v -- A1 dual-mode RUNTIME switching testbench (Task 76)
// -----------------------------------------------------------------------------
// Auto-generated by verify/gen_dual_tb.py -- DO NOT hand-edit.
//
// One physical unified_ntt instance, fixed to the SIGN datapath
// (BW=27, N_LAYERS=8), is reprogrammed at runtime between Kyber (KEM) and
// Dilithium (SIGN):
//   Phase A: cfg-load KEM constants re-derived for the 2^27 Montgomery radix
//            (QINV27=61403905, SCALE_K27=2811, zeta27 = zeta16*2^11 mod 3329)
//   Phase B: cfg-load SIGN constants + reload the 256-entry zeta ROM
//   Phase C: switch back to KEM and re-run Phase A bit-for-bit
// Constants derived and cross-checked in verify/kem27_model.py.
// =============================================================================

module tb_unified_ntt_dual;
    localparam BW     = 27;
    // KEM-on-2^27-radix constants (from verify/kem27_model.py)
    localparam Q_K    = 3329;
    localparam QINV_K = {qinv27};
    localparam SCALE_K_K = {scale_k27};
    localparam BM_K   = 20159;
    localparam SH_K   = 26;
    localparam NL_K   = 7;
    localparam R27    = 2435;        // 2^27 mod 3329
    // SIGN constants
    localparam Q_S    = 8380417;
    localparam QINV_S = 58728449;
    localparam SCALE_K_S = 49145;
    localparam BM_S   = 33587228;
    localparam SH_S   = 48;
    localparam NL_S   = 8;
    localparam R_S    = 131056;      // 2^27 mod 8380417

    reg clk = 0;
    reg rst_n = 0;
    reg start = 0;
    reg inverse = 0;
    wire busy;
    wire done;

    reg load = 0;
    reg [7:0] load_addr = 0;
    reg [BW-1:0] load_data = 0;
    reg [7:0] read_addr = 0;
    wire [BW-1:0] read_data;

    reg zeta_load = 0;
    reg [7:0] zeta_addr = 0;
    reg [BW-1:0] zeta_data = 0;

    reg cfg_load = 0;
    reg [2:0] cfg_addr = 0;
    reg [BW-1:0] cfg_data = 0;

    // -------------------------------------------------------------------------
    // DUT: compile-time SIGN defaults; runtime config reprograms it.
    // -------------------------------------------------------------------------
    unified_ntt #(
        .N(256), .N_LAYERS(8), .BW(BW),
        .Q(Q_S), .QINV(QINV_S), .R_MOD(R_S),
        .SCALE_K(SCALE_K_S), .BARRETT_M(BM_S), .BARRETT_SH(SH_S)
    ) dut (
        .clk(clk), .rst_n(rst_n),
        .start(start), .inverse(inverse),
        .busy(busy), .done(done),
        .load(load), .load_addr(load_addr), .load_data(load_data),
        .read_addr(read_addr), .read_data(read_data),
        .zeta_load(zeta_load), .zeta_addr(zeta_addr), .zeta_data(zeta_data),
        .cfg_load(cfg_load), .cfg_addr(cfg_addr), .cfg_data(cfg_data)
    );

    always #5 clk = ~clk;  // 100 MHz

    integer errors = 0;
    integer total_errors = 0;
    integer i;
    integer t;

    // zeta tables (parsed from the trusted legacy TBs, rescaled for 2^27)
{tbl_kem_zeta}

{tbl_sign_zeta}

    // input/output buffers
    reg [BW-1:0] f_buf    [0:255];
    reg [BW-1:0] orig_f   [0:255];
    reg [BW-1:0] coeff_out [0:255];
    reg [BW-1:0] phaseA_out [0:255];
    // SIGN golden vectors (from tb_unified_ntt_sign.v)
{tbl_sign_f1}

{tbl_sign_gold}

{tbl_sign_rng}

{tbl_kem_rng}

    // -------------------------------------------------------------------------
    // zeta pick: 0 -> KEM table (128 entries), 1 -> SIGN table (256 entries)
    // -------------------------------------------------------------------------
    function [BW-1:0] zpick;
        input integer idx;
        input integer is_sign;
        begin
            if (is_sign) zpick = sign_zeta[idx];
            else         zpick = kem_zeta[idx];
        end
    endfunction

    // -------------------------------------------------------------------------
    // All DUT inputs are negedge-aligned (see project TB rules): drive at
    // negedge, deassert at the following negedge -> exactly one sampling
    // posedge in between.
    // -------------------------------------------------------------------------
    task wait_done;
        integer guard;
        begin
            guard = 0;
            while (!done && guard < 500000) begin
                @(posedge clk); guard = guard + 1;
            end
            if (guard >= 500000) begin
                $display("ERROR: timeout waiting for done");
                errors = errors + 1;
            end
        end
    endtask

    task wr_cfg;
        input [2:0] a;
        input [BW-1:0] d;
        begin
            @(negedge clk);
            cfg_addr = a; cfg_data = d; cfg_load = 1'b1;
            @(negedge clk);
            cfg_load = 1'b0;
        end
    endtask

    task load_zeta_rom;
        input integer n;
        input integer is_sign;
        begin
            for (i = 0; i < n; i = i + 1) begin
                @(negedge clk);
                zeta_addr = i[7:0]; zeta_data = zpick(i, is_sign);
                zeta_load = 1'b1;
                @(negedge clk);
                zeta_load = 1'b0;
            end
        end
    endtask

    task load_poly;
        begin
            for (i = 0; i < 256; i = i + 1) begin
                @(negedge clk);
                load_addr = i[7:0]; load_data = f_buf[i]; load = 1'b1;
                @(negedge clk);
                load = 1'b0;
            end
        end
    endtask

    task read_poly;
        begin
            for (i = 0; i < 256; i = i + 1) begin
                @(negedge clk);
                read_addr = i[7:0];
                @(posedge clk);
                coeff_out[i] = read_data;
            end
        end
    endtask

    task run_ntt;
        input inv;
        begin
            @(negedge clk);
            start = 1'b1; inverse = inv;
            @(negedge clk);
            start = 1'b0;
            wait_done();
        end
    endtask

    task cfg_kem;
        begin
            wr_cfg(3'd0, Q_K);        // Q
            wr_cfg(3'd1, QINV_K);     // QINV (2^27 radix)
            wr_cfg(3'd2, SCALE_K_K);  // INTT scale
            wr_cfg(3'd3, BM_K);       // Barrett M
            wr_cfg(3'd4, SH_K);       // Barrett shift
            wr_cfg(3'd5, NL_K);       // N_LAYERS
        end
    endtask

    task cfg_sign;
        begin
            wr_cfg(3'd0, Q_S);
            wr_cfg(3'd1, QINV_S);
            wr_cfg(3'd2, SCALE_K_S);
            wr_cfg(3'd3, BM_S);
            wr_cfg(3'd4, SH_S);
            wr_cfg(3'd5, NL_S);
        end
    endtask

    // round-trip check: invntt(ntt(f)) == f * R mod q
    // (coeff_out holds the INTT result; orig_f holds the pristine input)
    task check_roundtrip;
        input [31:0] q;
        input [31:0] r_mod;
        begin
            errors = 0;
            for (i = 0; i < 256; i = i + 1) begin
                reg [63:0] prod64;
                reg [31:0] exp, got;
                integer s;
                prod64 = orig_f[i] * r_mod;
                exp = prod64 % q;
                // NB: `$signed(x) % q` mixes signed/unsigned and iverilog
                // zero-extends the signed operand, turning a negative
                // canonical output n into n + 2^BW (== exp + r_mod mod q).
                // Normalize by hand instead.
                s = $signed(coeff_out[i]);
                while (s < 0) s = s + q;
                while (s >= q) s = s - q;
                got = s;
                if (got != exp) begin
                    if (errors < 8)
                        $display("  RT-MISMATCH[%0d]: got %0d exp %0d",
                                 i, got, exp);
                    errors = errors + 1;
                end
            end
        end
    endtask

    // -------------------------------------------------------------------------
    // Main sequence
    // -------------------------------------------------------------------------
    initial begin
        rst_n = 0;
        repeat (5) @(posedge clk);
        rst_n = 1;
        repeat (2) @(posedge clk);

        // =====================================================================
        // Phase A: KEM at BW=27 / 2^27 Montgomery radix
        // =====================================================================
        $display("=== Phase A: KEM mode (q=3329, NL=7, 2^27 radix) ===");
        cfg_kem();
        load_zeta_rom(128, 0);

        // A1: forward NTT range check, f[i] = i
        for (i = 0; i < 256; i = i + 1) f_buf[i] = i[BW-1:0];
        load_poly();
        run_ntt(1'b0);
        read_poly();
        errors = 0;
        for (i = 0; i < 256; i = i + 1) begin
            if ($signed(coeff_out[i]) < -1664 || $signed(coeff_out[i]) > 1664) begin
                if (errors < 5)
                    $display("  RANGE-ERR[%0d] = %0d", i, $signed(coeff_out[i]));
                errors = errors + 1;
            end
        end
        if (errors == 0) $display("  PASS A1: forward coeffs in [-q/2, q/2]");
        else begin
            $display("  FAIL A1: %0d out of range", errors);
            total_errors = total_errors + errors;
        end

        // A2: round-trip on the LCG polynomial, save outputs for Phase C
        for (i = 0; i < 256; i = i + 1) f_buf[i] = kem_rng[i];
        for (i = 0; i < 256; i = i + 1) orig_f[i] = kem_rng[i];
        load_poly();
        run_ntt(1'b0);
        read_poly();
        for (i = 0; i < 256; i = i + 1) f_buf[i] = coeff_out[i];
        load_poly();
        run_ntt(1'b1);
        read_poly();
        for (i = 0; i < 256; i = i + 1) phaseA_out[i] = coeff_out[i];
        check_roundtrip(Q_K, R27);
        if (errors == 0) $display("  PASS A2: invntt(ntt(f)) == f*2^27 mod q (256/256)");
        else begin
            $display("  FAIL A2: %0d mismatches", errors);
            total_errors = total_errors + errors;
        end

        // A3: INTT(0) == 0
        for (i = 0; i < 256; i = i + 1) f_buf[i] = 0;
        load_poly();
        run_ntt(1'b0);
        read_poly();
        for (i = 0; i < 256; i = i + 1) f_buf[i] = coeff_out[i];
        load_poly();
        run_ntt(1'b1);
        read_poly();
        errors = 0;
        for (i = 0; i < 256; i = i + 1) begin
            reg [31:0] got;
            integer s;
            s = $signed(coeff_out[i]);
            while (s < 0) s = s + Q_K;
            while (s >= Q_K) s = s - Q_K;
            got = s;
            if (got != 0) errors = errors + 1;
        end
        if (errors == 0) $display("  PASS A3: invntt(ntt(0)) == 0");
        else begin
            $display("  FAIL A3: %0d non-zero", errors);
            total_errors = total_errors + errors;
        end

        // A4: non-trivial forward (f[i]=i+1)
        for (i = 0; i < 256; i = i + 1) f_buf[i] = i + 1;
        load_poly();
        run_ntt(1'b0);
        read_poly();
        errors = 0;
        for (i = 0; i < 256; i = i + 1)
            if ($signed(coeff_out[i]) !== 0) errors = errors + 1;
        if (errors > 100)
            $display("  PASS A4: forward NTT non-trivial (%0d non-zero)", errors);
        else
            $display("  FAIL A4: mostly zero (%0d non-zero)", errors);

        // =====================================================================
        // Phase B: SIGN (q=8380417, NL=8)
        // =====================================================================
        $display("=== Phase B: SIGN mode (q=8380417, NL=8) ===");
        cfg_sign();
        load_zeta_rom(256, 1);

        // B1: forward NTT bit-exact vs the SIGN golden vector
        for (i = 0; i < 256; i = i + 1) f_buf[i] = sign_f1[i];
        load_poly();
        run_ntt(1'b0);
        read_poly();
        errors = 0;
        for (i = 0; i < 256; i = i + 1) begin
            if (coeff_out[i] !== sign_gold[i]) begin
                if (errors < 8)
                    $display("  B1-MISMATCH[%0d]: got %0d exp %0d", i,
                             $signed(coeff_out[i]), $signed(sign_gold[i]));
                errors = errors + 1;
            end
        end
        if (errors == 0)
            $display("  PASS B1: SIGN forward NTT bit-exact vs gold (256/256)");
        else begin
            $display("  FAIL B1: %0d mismatches", errors);
            total_errors = total_errors + errors;
        end

        // B2: range check on the B1 output
        errors = 0;
        for (i = 0; i < 256; i = i + 1)
            if ($signed(coeff_out[i]) < -(Q_S/2) || $signed(coeff_out[i]) > Q_S/2)
                errors = errors + 1;
        if (errors == 0) $display("  PASS B2: SIGN coeffs in [-q/2, q/2]");
        else begin
            $display("  FAIL B2: %0d out of range", errors);
            total_errors = total_errors + errors;
        end

        // B3: round-trip on a wide pseudo-random polynomial
        for (i = 0; i < 256; i = i + 1) f_buf[i] = sign_rng[i];
        for (i = 0; i < 256; i = i + 1) orig_f[i] = sign_rng[i];
        load_poly();
        run_ntt(1'b0);
        read_poly();
        for (i = 0; i < 256; i = i + 1) f_buf[i] = coeff_out[i];
        load_poly();
        run_ntt(1'b1);
        read_poly();
        check_roundtrip(Q_S, R_S);
        if (errors == 0)
            $display("  PASS B3: invntt(ntt(f)) == f*2^27 mod q (256/256)");
        else begin
            $display("  FAIL B3: %0d mismatches", errors);
            total_errors = total_errors + errors;
        end

        // =====================================================================
        // Phase C: switch back to KEM, re-run Phase A2, must match bit-for-bit
        // =====================================================================
        $display("=== Phase C: KEM again (switch-back consistency) ===");
        cfg_kem();
        load_zeta_rom(128, 0);
        for (i = 0; i < 256; i = i + 1) f_buf[i] = kem_rng[i];
        load_poly();
        run_ntt(1'b0);
        read_poly();
        for (i = 0; i < 256; i = i + 1) f_buf[i] = coeff_out[i];
        load_poly();
        run_ntt(1'b1);
        read_poly();
        errors = 0;
        for (i = 0; i < 256; i = i + 1) begin
            if (coeff_out[i] !== phaseA_out[i]) begin
                if (errors < 8)
                    $display("  C-MISMATCH[%0d]: got %0d phaseA %0d", i,
                             $signed(coeff_out[i]), $signed(phaseA_out[i]));
                errors = errors + 1;
            end
        end
        if (errors == 0)
            $display("  PASS C: KEM->SIGN->KEM round-trip bit-identical (256/256)");
        else $display("  FAIL C: %0d mismatches", errors);

        if (errors == 0)
            $display("\\nRESULT: DUAL-MODE ALL PASS");
        else
            $display("\\nRESULT: DUAL-MODE FAILURES (%0d)", errors);
        $finish;
    end

endmodule
""".format(
        qinv27=k27["qinv"], scale_k27=k27["scale_k"],
        tbl_kem_zeta=table_decl("kem_zeta", zeta27, 128),
        tbl_sign_zeta=table_decl("sign_zeta", sign_zeta, 256),
        tbl_sign_f1=table_decl("sign_f1", [v & MASK for v in f1], 256),
        tbl_sign_gold=table_decl("sign_gold", [v & MASK for v in gold_ntt], 256),
        tbl_sign_rng=table_decl("sign_rng", rng27, 256),
        tbl_kem_rng=table_decl("kem_rng", rng, 256),
    )

    with open(TB_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    print("wrote %s (%d bytes)" % (TB_PATH, len(src)))
    print("KEM27: QINV=%d SCALE_K=%d zeta27[0..3]=%s"
          % (k27["qinv"], k27["scale_k"], zeta27[:4]))


if __name__ == "__main__":
    main()
