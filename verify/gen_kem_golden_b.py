"""
Second ML-KEM-768 golden vector set for multi-vector verification.
Differs from gen_kem_golden.py only in the RNG seed and the '_b' filename
suffix. The purpose is to prove the RTL is correct for a second independent
seed/message pair (guards against data-dependent bugs that a single-vector
test would hide).

Seeds:
  A-set: random.seed(20261007)  -- generated by gen_kem_golden.py
  B-set: random.seed(20261009)  -- generated by THIS script
"""
import sys, os, hashlib, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kem_ref as K


def poly_to_hex(poly, name, outdir):
    path = os.path.join(outdir, f"{name}.hex")
    with open(path, "w") as f:
        for x in poly:
            f.write(f"{x & 0xFFFF:04x}")
    return path


def main():
    outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sim")
    os.makedirs(outdir, exist_ok=True)

    # Independent seed from the A-set (20261007)
    random.seed(20261009)
    d0 = random.randbytes(32)
    pk, sk = K.keygen(d0)
    m0 = random.randbytes(32)
    ct, ss_e = K.encaps(pk, m0)
    ss_d, m_rec = K.decaps(sk, ct)

    t, rho = pk
    d, s, rho_sk = sk

    # Scalar seeds
    with open(os.path.join(outdir, "kem_d0_b.hex"), "w") as f:
        f.write(d0.hex())
    with open(os.path.join(outdir, "kem_m0_b.hex"), "w") as f:
        f.write(m0.hex())
    with open(os.path.join(outdir, "kem_rho_b.hex"), "w") as f:
        f.write(rho.hex())
    with open(os.path.join(outdir, "kem_sigma_b.hex"), "w") as f:
        f.write(hashlib.shake_256(d0).digest(64)[32:].hex())

    # Public key polys
    for i in range(K.K):
        poly_to_hex(t[i], f"kem_t{i}_b", outdir)
    for i in range(K.K):
        poly_to_hex(s[i], f"kem_s{i}_b", outdir)

    # Ciphertext polys
    cu, cv = ct
    for i in range(K.K):
        poly_to_hex(cu[i], f"kem_cu{i}_b", outdir)
    poly_to_hex(cv, "kem_cv_b", outdir)

    # Shared secret + recovered message
    with open(os.path.join(outdir, "kem_ss_b.hex"), "w") as f:
        f.write(ss_e.hex())
    with open(os.path.join(outdir, "kem_mrec_b.hex"), "w") as f:
        f.write(m_rec.hex())

    print("KEM golden vectors B-set generated.")
    print(f"  seed    = {20261009}")
    print(f"  d0[0..3] = {d0[:4].hex()}")
    print(f"  m0[0..3] = {m0[:4].hex()}")
    print(f"  ss_e[0..3]= {ss_e[:4].hex()}")
    print(f"  ss_d[0..3]= {ss_d[:4].hex()}")
    print(f"  round-trip: {'PASS' if ss_e == ss_d else 'FAIL'}")


if __name__ == "__main__":
    main()
