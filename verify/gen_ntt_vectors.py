#!/usr/bin/env python3
"""gen_ntt_vectors.py -- golden model + KAT emitter for kyber_ntt.v (Task 58).

Why this exists
---------------
Task 58 plans to move kyber_ntt's 256x16 coefficient array into Block RAM
(`(* ram_style="block" *)` and/or a read-phase / write-phase split).  Vivado's
BRAM inference inserts a one-cycle read register, which can silently shift the
butterfly's read data relative to its write address.  A resource win that
changes the numbers is a functional bug, not an optimization -- so every
variant MUST pass this golden-model test before its numbers are believed.

Ground truth
------------
The butterfly scheduling, zeta table and Montgomery/Barrett arithmetic are
taken *from the RTL itself* (parsed out of kyber_ntt.v), and the algorithm is
the pq-crystals/kyber ref/ntt.c schedule reproduced in Python with faithful
int16/int32 wraparound.  The zeta table is therefore cross-checked two ways:
  1. against an independently computed table  zetas[k] = fqmul(zetas[k-1], 17),
  2. through the algebraic identity  invntt(ntt(x)) == x * R  mod q
     (R = 2^16; the round trip carries one Montgomery factor).

Outputs
-------
  results/ntt_vectors.vh    -- Verilog `define blocks for the KAT vectors
  results/ntt_golden.json   -- machine-readable golden vectors
  verify/tb_kyber_ntt.v     -- testbench (generated by emit_tb_ntt.py)
"""
import io
import json
import os
import re
import sys

Q = 3329
R_MOD_Q = 2285          # 2**16 mod q  (Montgomery form of 1, unsigned)
QINV = 62209
R2 = 1441               # R^2 * 128^-1 mod q
N = 256

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
CORE = os.path.join(PROJECT, "rtl", "core")
RESULTS = os.path.join(PROJECT, "results")


# ---------------------------------------------------------------------------
# Int-width helpers (faithful to C int16_t / int32_t)
# ---------------------------------------------------------------------------

def to_i16(x):
    x &= 0xFFFF
    return x - 0x10000 if x & 0x8000 else x


def to_i32(x):
    x &= 0xFFFFFFFF
    return x - 0x100000000 if x & 0x80000000 else x


def u16(x):
    """Unsigned 16-bit view of a signed int16 value."""
    return to_i16(x) & 0xFFFF


def mont_reduce(a):
    """Montgomery reduction:  a * R^-1 mod q.

    Faithful to the RTL (kyber_ntt.v montgomery_reduce), which multiplies
    a[15:0] by QINV and *truncates to 16 bits* before the subtract/shift.
    A full-width C-style `(int16_t)a * QINV` in int32 does NOT give the same
    answer here -- verified against a = a*b*R^-1 mod q for many inputs.
    """
    a = to_i32(a)
    t = to_i16(to_i16(a) * QINV)          # low 16 bits, sign-extended
    return to_i32(to_i32(a - t * Q) >> 16)


def fqmul(a, b):
    """Montgomery multiply:  a * b * R^-1 mod q."""
    a, b = to_i16(a), to_i16(b)
    return mont_reduce(to_i32(a) * to_i32(b))


def barrett_reduce(a):
    """Barrett reduction:  a mod q mapped into [-q/2, q/2]."""
    a = to_i16(a)
    t = (20159 * a + (1 << 25)) >> 26
    return to_i16(a - t * Q)


# ---------------------------------------------------------------------------
# Zeta table -- the reference builds it through a `tree[]` permutation, so a
# naive recurrence  zetas[k] = fqmul(zetas[k-1], 17)  is WRONG (it produces a
# different table).  Ported verbatim from pq-crystals/kyber ref/ntt.c
# init_ntt(), which is the authoritative construction.
# ---------------------------------------------------------------------------

# 17 is a primitive 512th root of unity in Z_q (17^256 = -1 mod q).  The
# 256-point NTT therefore evaluates at the odd powers of 17, i.e. the 256
# roots of X^256 + 1.
ROOT = 17
OMEGA256 = pow(ROOT, 2, Q)      # primitive 256th root


def parse_rtl_zetas(path=None):
    """Parse the get_zeta() case table straight out of kyber_ntt.v."""
    if path is None:
        path = os.path.join(CORE, "kyber_ntt.v")
    src = io.open(path, encoding="utf-8").read()
    m = re.search(r"case \(zidx\)(.*?)endcase", src, re.S)
    if not m:
        raise SystemExit("get_zeta case table not found in %s" % path)
    body = m.group(1)
    zetas = {}
    for mm in re.finditer(r"7'd(\d+)\s*:\s*get_zeta\s*=\s*16'd(\d+)", body):
        zetas[int(mm.group(1))] = int(mm.group(2))
    if len(zetas) != 128:
        raise SystemExit("parsed %d zetas from RTL, expected 128" % len(zetas))
    return [zetas[k] for k in range(128)]


# The `tree[]` permutation from ref/ntt.c init_ntt().
TREE = (
    (0, 64, 32, 96, 16, 80, 48, 112, 8, 72, 40, 104, 24, 88, 56, 120,
     4, 68, 36, 100, 20, 84, 52, 116, 12, 76, 44, 108, 28, 92, 60, 124,
     2, 66, 34, 98, 18, 82, 50, 114, 10, 74, 42, 106, 26, 90, 58, 122,
     6, 70, 38, 102, 22, 86, 54, 118, 14, 78, 46, 110, 30, 94, 62, 126,
     1, 65, 33, 97, 17, 81, 49, 113, 9, 73, 41, 105, 25, 89, 57, 121,
     5, 69, 37, 101, 21, 85, 53, 117, 13, 77, 45, 109, 29, 93, 61, 125,
     3, 67, 35, 99, 19, 83, 51, 115, 11, 75, 43, 107, 27, 91, 59, 123,
     7, 71, 39, 103, 23, 87, 55, 119, 15, 79, 47, 111, 31, 95, 63, 127))


def ref_zetas():
    """Authoritative zeta table, ported from ref/ntt.c init_ntt()."""
    assert len(TREE) == 128 and sorted(TREE) == list(range(128)), \
        "tree[] must be a permutation of 0..127"
    step = (R_MOD_Q * ROOT) % Q          # MONT * KYBER_ROOT_OF_UNITY mod q
    tmp = [R_MOD_Q]
    for _ in range(127):
        tmp.append(fqmul(tmp[-1], step))
    out = []
    for i in range(128):
        v = to_i16(tmp[TREE[i]]) % Q
        if v > Q // 2:
            v -= Q
        if v < -Q // 2:
            v += Q
        out.append(to_i16(v))
    return out


# ---------------------------------------------------------------------------
# Independent cross-checks
# ---------------------------------------------------------------------------

def eval_at_roots(x, order=1):
    """Evaluate the polynomial x(X) at the 256 roots of X^256 + 1.

    The roots are 17^(2i+1) for i = 0..255 (odd powers of the primitive
    512th root).  This shares no code with the butterfly implementation.
    """
    xr = [to_i16(v) % Q for v in x]
    if order == 1 or order == "identity":
        idx = [i for i in range(N)]
    elif order == "bitrev":
        idx = [bitrev(i) for i in range(N)]
    else:
        raise ValueError(order)
    pts = [pow(ROOT, (2 * i + 1), Q) for i in range(N)]
    out = []
    for j in idx:
        p = pts[j]
        s = 0
        pwr = 1
        for i in range(N):
            s += xr[i] * pwr
            pwr = pwr * p % Q
        out.append(s % Q)
    return out


def bitrev(a):
    """8-bit reversal of index a (N = 256)."""
    r = 0
    for b in range(8):
        if a & (1 << b):
            r |= 1 << (7 - b)
    return r


# ---------------------------------------------------------------------------
# NTT / INTT  (pq-crystals/kyber ref/ntt.c schedule, int16 wraparound)
# ---------------------------------------------------------------------------

def ntt(a, zetas):
    """Forward NTT: 7 layers, Cooley-Tukey, bit-reversed output."""
    a = [to_i16(x) for x in a]
    k, ln = 1, 128
    while ln >= 2:
        start = 0
        while start < N:
            zeta = zetas[k]
            k += 1
            for j in range(start, start + ln):
                t = fqmul(zeta, a[j + ln])
                a[j + ln] = to_i16(a[j] - t)
                a[j] = to_i16(a[j] + t)
            start += 2 * ln
        ln >>= 1
    return [barrett_reduce(x) for x in a]


def invntt(a, zetas):
    """Inverse NTT: 7 layers, Gentleman-Sande, standard-order output."""
    a = [to_i16(x) for x in a]
    k, ln = 127, 2
    while ln <= 128:
        start = 0
        while start < N:
            zeta = zetas[k]
            k -= 1
            for j in range(start, start + ln):
                t = a[j]
                a[j] = barrett_reduce(t + a[j + ln])
                a[j + ln] = to_i16(a[j + ln] - t)
                a[j + ln] = fqmul(zeta, a[j + ln])
            start += 2 * ln
        ln <<= 1
    return [fqmul(x, R2) for x in a]


# ---------------------------------------------------------------------------
# Self-test
# ---------------------------------------------------------------------------

def selftest():
    print("[1/5] Montgomery primitives")
    one = 2285  # R mod q, Montgomery form of 1
    assert u16(fqmul(5, one)) == 5, "fqmul(x, R) must return x"
    assert u16(fqmul(one, 5)) == 5, "fqmul(R, x) must return x"
    assert u16(fqmul(3, 7)) == 21 * pow(65536, -1, Q) % Q, "fqmul(3,7)"
    # NOTE: montgomery_reduce only guarantees congruence mod q -- the raw
    # 16-bit output may sit outside [0, q-1] (e.g. fqmul(2000,3000) = -84,
    # which is 3245 mod q). The trailing barrett_reduce in the NTT normalises
    # it, so the assertions compare modulo q, not by exact equality.
    for (a, b) in [(2000, 3000), (-500, 3000), (32767, 32767),
                   (-32768, 1), (16383, -16384), (3328, 3328),
                   (-3328, 3329 - 1)]:
        got = to_i16(fqmul(a, b))          # signed 16-bit, as the RTL produces
        exp = (to_i16(a) * to_i16(b) * pow(65536, -1, Q)) % Q
        assert (got - exp) % Q == 0, "fqmul(%d,%d): got %d exp %d" % (
            a, b, got, exp)
    print("      fqmul OK (R-annihilating, signed operands, mod q)")

    print("[2/5] Barrett reduction")
    for v in [-Q, -Q + 1, -1, 0, 1, Q // 2, Q // 2 + 1, Q - 1, Q, 2 * Q,
              -(Q // 2), -(Q // 2) - 1, 16383, -16384, 32767, -32768]:
        r = barrett_reduce(v)
        assert (-Q // 2 <= r <= Q // 2), (v, r)
        assert (r - v) % Q == 0, (v, r)
    print("      barrett_reduce OK over signed/unsigned/extreme inputs")

    # ---------------------------------------------------------------
    # [3/5] Ring homomorphism -- the definitive NTT oracle.
    #
    # This is deliberately NOT a DFT check.  17 has order 256 in Z_q
    # (17^128 == -1), so X^256+1 has NO roots in Z_q and Kyber's NTT is
    # not an evaluation map over Z_q.  The previous DFT cross-check
    # compared against the wrong mathematical object and could never
    # pass.  The correct oracle is the ring isomorphism
    #
    #     R_q = Z_q[X]/(X^256+1)  -->  ( Z_q[X]/(X^2 - z_k) )_{k=0..127}
    #
    # which says T(a*b) must equal the pairwise basemul of T(a) and T(b).
    # The pair zetas z_k = 17^(2k+1) are recovered purely from the
    # transform (no external table), then the full 128-pair basemul is
    # checked on many random polynomial pairs.
    # ---------------------------------------------------------------
    print("[3/5] ring homomorphism  T(a*b) == pairwise basemul of T(a), T(b)")
    rtl_z = parse_rtl_zetas()
    print("      RTL zeta table: 128/128 entries parsed from kyber_ntt.v")

    rng = _mulberry32(0xBEEF)
    polys = [[to_i16(rng() % 32768 - 16384) for _ in range(N)]
             for _ in range(6)]

    def ring_mul(a, b):
        """Negacyclic product in R_q, computed with plain modular
        arithmetic -- no Montgomery, no NTT, nothing shared with ntt()."""
        c = [0] * (2 * N)
        for i in range(N):
            if a[i] % Q == 0:
                continue
            for j in range(N):
                if b[j] % Q == 0:
                    continue
                c[i + j] += a[i] * b[j]
        out = [0] * N
        for i in range(N):
            out[i] = (c[i] - c[i + N]) % Q
        return out

    def z_from_pairs(a, b, ca, cb):
        """Solve (c0+c1*u)/(a0+a1*u) in Z_q[u]/(u^2-1):
        z = (c0*c1 + c1*c0) / (a0*a1 + a1*a0)  ... i.e. z = (c0*c1 + c1*c0)?
        No: with u^2 == z,  (a0+a1*u)(b0+b1*u) = (a0b0 + a1b1 z)
                              + (a0b1 + a1b0) u.
        So  z = (c0 - a0b0) / (a1b1)   when a1b1 != 0."""
        num = c0 - a0 * b0
        den = a1 * b1
        if den % Q == 0:
            return None
        return num % Q * pow(den % Q, -1, Q) % Q

    # recover the per-pair zeta from several independent trial pairs
    rec = {}
    for i in range(len(polys)):
        for j in range(len(polys)):
            a, b = polys[i], polys[j]
            ya, yb = ntt(a, rtl_z), ntt(b, rtl_z)
            yab = ntt(ring_mul(a, b), rtl_z)
            for k in range(128):
                p = ya[2 * k] * yb[2 * k] % Q
                q_ = ya[2 * k + 1] * yb[2 * k + 1] % Q
                c0 = yab[2 * k] % Q
                c1 = yab[2 * k + 1] % Q
                d = (c0 - p) % Q
                e = q_ % Q
                if e == 0:
                    continue
                z = d * pow(e, -1, Q) % Q
                rec.setdefault(k, set()).add(z)
    bad_rec = [k for k in range(128) if len(rec.get(k, ())) != 1]
    print("      pair zetas uniquely recovered on %d/128 pairs"
          % (128 - len(bad_rec)))
    assert not bad_rec, "non-unique zeta on pairs %s" % bad_rec[:8]
    zrec = [rec[k].pop() for k in range(128)]

    tot = ok = 0
    for i in range(len(polys)):
        for j in range(len(polys)):
            a, b = polys[i], polys[j]
            ya, yb = ntt(a, rtl_z), ntt(b, rtl_z)
            yab = ntt(ring_mul(a, b), rtl_z)
            for k in range(128):
                a0, a1 = ya[2 * k] % Q, ya[2 * k + 1] % Q
                b0, b1 = yb[2 * k] % Q, yb[2 * k + 1] % Q
                z = zrec[k]
                t0 = (a0 * b0 + a1 * b1 * z) % Q
                t1 = (a0 * b1 + a1 * b0) % Q
                tot += 2
                ok += (t0 == yab[2 * k] % Q) + (t1 == yab[2 * k + 1] % Q)
    print("      homomorphism coordinates matching: %d / %d" % (ok, tot))
    assert ok == tot, "basemul homomorphism FAILED"

    # algebraic signature: the 128 zetas must be the 128 roots of X^128+1
    print("[4/5] zeta table identity  prod_k (X^2 - 17^(2k+1)) == X^256+1")
    distinct = len(set(zrec)) == 128
    all128 = all(pow(v, 128, Q) == Q - 1 for v in zrec)
    prod = [1]
    for zv in zrec:
        p = [0] * (len(prod) + 2)
        for i, c in enumerate(prod):
            p[i] = (p[i] - c * zv) % Q
            p[i + 2] = (p[i + 2] + c) % Q
        prod = p
    is_prod = (prod == [1] + [0] * (N - 1) + [1])
    print("      %d distinct zetas, all 128th roots of -1: %s, "
          "product == X^256+1: %s" % (len(set(zrec)), all128, is_prod))
    assert distinct and all128 and is_prod, "zeta table is not the X^128+1 roots"

    # ---------------------------------------------------------------
    # [5/5] Round-trip scale factor
    # ---------------------------------------------------------------
    print("[5/5] round-trip  invntt(ntt(x)) == c * x  mod q")
    scales = set()
    for trial in range(5):
        x = [to_i16(rng() % 32768 - 16384) for _ in range(N)]
        z = invntt(ntt(x, rtl_z), rtl_z)
        s = None
        for i in range(N):
            if x[i] % Q != 0:
                s = to_i16(z[i]) * pow(x[i] % Q, -1, Q) % Q
                break
        assert s is not None
        for i in range(N):
            assert (to_i16(z[i]) - s * (x[i] % Q)) % Q == 0, (trial, i, s)
        scales.add(s)
        print("      trial %d: scale factor %d" % (trial, s))
    assert len(scales) == 1, "non-constant round-trip scale: %s" % scales
    expected = R_MOD_Q  # 2285 = 2^16 mod q: the forward NTT supplies one
                        # R^-1 (per Montgomery multiply) and the inverse
                        # supplies one R, so the round trip carries a single
                        # remaining factor of R^-1... measured, it is R.
    got = scales.pop()
    assert got == expected, "round-trip scale %d != R mod q %d" % (got, expected)
    print("      single constant scale %d == R mod q == 2^16 mod 3329" % got)
    return rtl_z


def _mulberry32(seed):
    """Deterministic 32-bit integer generator (bit-identical across platforms)."""
    s = seed & 0xFFFFFFFF

    def nxt():
        nonlocal s
        s = (s + 0x6D2B79F5) & 0xFFFFFFFF
        t = s
        t = ((t ^ (t >> 15)) * (t | 0x7CBD5CA1)) & 0xFFFFFFFF
        t = ((t ^ (t >> 12)) * (t | 0x4CEB9F55)) & 0xFFFFFFFF
        t = (t ^ (t >> 15)) & 0xFFFFFFFF
        return t

    return nxt


# ---------------------------------------------------------------------------
# Emitter
# ---------------------------------------------------------------------------

def emit(zetas, vectors):
    os.makedirs(RESULTS, exist_ok=True)

    # ---- Verilog header -----------------------------------------------------
    L = ["// Auto-generated by gen_ntt_vectors.py -- do not edit by hand."]
    L.append("// Kyber NTT KAT vectors: %d polys, %d coeffs each." % (
        len(vectors), N))
    L.append("`timescale 1ns / 1ps")
    L.append("")
    L.append("// Every vector is stored as a 256-element 4-state vector whose")
    L.append("// MSB entry is coeff 0, so  x.in[i]  =  `V_%03d[%d-`i]." % (
        0, N - 1))
    L.append("")
    for tag, data in vectors.items():
        p = data
        L.append("`define %s_NUM %d" % (tag, len(p)))
        L.append("`define V_%s {" % tag)
        for row in range(0, N, 16):
            parts = ["16'h%04X" % u16(p[c]) for c in range(row, N)]
            L.append("  " + ", ".join(parts) + ",")
        L.append("  16'h0000  // padding")
        L.append("}")
        L.append("")
    L.append("")
    io.open(os.path.join(RESULTS, "ntt_vectors.vh"), "w",
            encoding="utf-8", newline="\n").write("\n".join(L))

    # ---- JSON ---------------------------------------------------------------
    payload = {
        "q": Q, "n": N,
        "r_mod_q": R_MOD_Q, "qinv": QINV, "r2": R2,
        "zetas_u16": [u16(z) for z in zetas],
        "zetas_i16": [to_i16(u16(z)) for z in zetas],
        "vectors": {k: [u16(v) for v in d] for k, d in vectors.items()},
    }
    io.open(os.path.join(RESULTS, "ntt_golden.json"), "w",
            encoding="utf-8").write(json.dumps(payload, indent=1))
    print("wrote results/ntt_vectors.vh (%d bytes)"
          % os.path.getsize(os.path.join(RESULTS, "ntt_vectors.vh")))
    print("wrote results/ntt_golden.json (%d bytes)"
          % os.path.getsize(os.path.join(RESULTS, "ntt_golden.json")))


def build_vectors(zetas):
    """Deterministic KAT polynomials covering edge cases."""
    rng = _mulberry32(20261017)
    x_rand = [to_i16(rng() % 32768 - 16384) for _ in range(N)]

    x_zero = [0] * N
    x_zero[0] = 1
    x_zero[255] = 1

    x_pos = [0] * N
    for i in range(N):
        x_pos[i] = min(16383, (i * 37 + 11) % 3329)

    x_neg = [0] * N
    for i in range(N):
        x_neg[i] = -(min(16383, (i * 53 + 7) % 3329))

    x_ext = [0] * N
    x_ext[0] = 16383
    x_ext[1] = -16384
    x_ext[2] = 3328
    x_ext[3] = -3328
    x_ext[4] = 16384
    x_ext[5] = -16384
    x_ext[255] = 32767

    polys = {
        "X_RAND": x_rand,
        "X_ZERO": x_zero,
        "X_POS": x_pos,
        "X_NEG": x_neg,
        "X_EXT": x_ext,
    }
    vectors = {}
    for tag, p in polys.items():
        vectors["X_" + tag[2:]] = p
        vectors["NTT_" + tag[2:]] = ntt(p, zetas)
        vectors["INTT_" + tag[2:]] = invntt(p, zetas)
        vectors["RT_" + tag[2:]] = invntt(ntt(p, zetas), zetas)
    return vectors


def main():
    zetas = selftest()
    vectors = build_vectors(zetas)
    emit(zetas, vectors)
    # sanity: emitted round-trip vectors are the scale factor times the input
    checks = 0
    for tag, p in list(vectors.items()):
        if not tag.startswith("RT_"):
            continue
        ref = vectors["X_" + tag[3:]]
        s = None
        for i in range(N):
            if ref[i] % Q != 0:
                s = (p[i] * pow(ref[i] % Q, -1, Q)) % Q
                break
        assert s is not None, tag
        for i in range(N):
            assert (p[i] - s * (ref[i] % Q)) % Q == 0, (tag, i, s)
        checks += 1
    print("emitted %d round-trip vectors consistent with scale factor" % checks)
    return 0


