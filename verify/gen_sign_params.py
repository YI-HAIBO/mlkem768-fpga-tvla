"""Generate the exact SIGN-mode (Dilithium / ML-DSA) constants for unified_ntt.v.

Outputs:
  - QINV, R_MOD, SCALE_K, BARRETT_M, BARRETT_SH  (BW = 27)
  - the 256-entry zeta ROM in R = 2^27 Montgomery form (signed, two's complement)
and writes rtl/core/dilithium_sign_params.vh (a Verilog include with the ROM as a
loadable array) + prints the values for embedding in the TB.

The ring twiddles are R-independent: zeta_k = DILITHIUM_ZETAS[k] * 2^-32  mod q
(Dilithium reference uses 32-bit Montgomery).  The RTL/SIGN domain uses R = 2^27,
so zetas_m[k] = zeta_k * 2^27  mod q.
"""
from ntt_model import DILITHIUM_ZETAS

QD = 8380417
BW = 27
Rref_bits = 32
W_WIDTH = 2 * BW          # 54
SH = 48
M = (1 << SH) // QD       # floor(2^48 / q) -- exact Barrett for q and our value range

QINV = pow(QD, -1, 1 << BW)        # q^-1 mod 2^27
R_MOD = pow(2, BW, QD)             # 2^27 mod q = 16382
Rinv_ref = pow(2, -Rref_bits, QD)
Rm = pow(2, BW, QD)

# ring twiddle (R-independent) then Montgomery-convert into the R=2^BW domain
zetas_m = []
for k in range(len(DILITHIUM_ZETAS)):
    zk = (DILITHIUM_ZETAS[k] % QD) * Rinv_ref % QD      # true ring twiddle
    zetas_m.append((zk * Rm) % QD)

# signed two's-complement 27-bit representation for Verilog
def s27(v):
    v %= QD
    return v - (1 << BW) if v >= (1 << (BW - 1)) else v

zetas_signed = [s27(z) for z in zetas_m]

# derive SCALE_K directly: invntt(ntt(e0))[0] = C, then SCALE_K = R^2 * C^-1
from ntt_model import RTLNTT
d = RTLNTT(q=QD, bw=BW, layers=8, bm=M, bsh=SH, scale_k=1)
e0 = [0] * 256
e0[0] = 1
fwd, _ = d.ntt(zetas_m, e0)
raw, _ = d.invntt_raw(zetas_m, fwd)
C = raw[0] % QD
SCALE_K = (R_MOD * R_MOD % QD) * pow(C, -1, QD) % QD

print("QD        =", QD)
print("BW        =", BW, " W_WIDTH =", W_WIDTH)
print("QINV      =", QINV, " (q^-1 mod 2^27)")
print("R_MOD     =", R_MOD, " (2^27 mod q)")
print("BARRETT_M =", M, " BARRETT_SH =", SH)
print("SCALE_K   =", SCALE_K)
print("C (invntt(ntt(e0))[0]) =", C)
print("zeta[0..3]   =", zetas_signed[:4])
print("zeta[252..255]=", zetas_signed[252:])

# sanity: rebuild model and confirm round-trip
d.scale_k = SCALE_K
import random
random.seed(1)
bad = 0
peak = 0
for _ in range(300):
    f = [random.randint(0, QD - 1) for _ in range(256)]
    out, _ = d.ntt(zetas_m, f)
    back, _ = d.invntt(zetas_m, out)
    peak = max(peak, max(abs(x) for x in out))
    if not all((back[i] % QD) == (f[i] * R_MOD) % QD for i in range(256)):
        bad += 1
print("round-trip failures =", bad, "  peak fwd |value| =", peak)

# write the Verilog include (ROM as a loadable array for the TB)
lines = []
lines.append("// Auto-generated by gen_sign_params.py -- SIGN mode zeta ROM (R=2^27).")
lines.append("// 256 entries, signed 27-bit two's complement, one per line.")
lines.append("localparam integer SIGN_BW        = 27;")
lines.append("localparam integer SIGN_QINV     = %d;" % QINV)
lines.append("localparam integer SIGN_R_MOD    = %d;" % R_MOD)
lines.append("localparam integer SIGN_SCALE_K  = %d;" % SCALE_K)
lines.append("localparam integer SIGN_BM       = %d;" % M)
lines.append("localparam integer SIGN_BSH      = %d;" % SH)
lines.append("reg signed [SIGN_BW-1:0] sign_zeta [0:255];")
lines.append("initial begin")
for k, z in enumerate(zetas_signed):
    lines.append("  sign_zeta[%d] = %d'sd %d;" % (k, BW, z))
lines.append("end")
with open("dilithium_sign_params.vh", "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("\nwrote dilithium_sign_params.vh (", len(zetas_signed), "entries )")

# also stash raw signed list for the TB generator
with open("sign_zeta_list.txt", "w") as fh:
    fh.write(",".join(str(z) for z in zetas_signed))
