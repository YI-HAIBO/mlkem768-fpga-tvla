"""Generate sim/tb_unified_ntt_sign.v : bit-exact SIGN-mode testbench for unified_ntt.

Verifies (against a Python golden that mirrors the RTL arithmetic exactly):
  Test 1: forward NTT bit-exact vs golden                (256 coeffs)
  Test 2: forward output in [-q/2, q/2]
  Test 3: invntt(ntt(f)) == f * R (mod q)  for 5 hardcoded polynomials
  Test 4: invntt(ntt(0)) == 0
  Test 5: INTT(gold_ntt) == f1 * R  -- isolates the inverse path
  Test 6: invntt(ntt(a) o ntt(b)) == a*b*R  vs schoolbook negacyclic convolution
The module under test: unified_ntt with SIGN params (q=8380417, BW=27, 8 layers,
W_WIDTH=54, SCALE_K=49145, Barrett SH=48).

NOTE: every f*R expectation is computed through a 64-bit intermediate.  A
`reg [31:0]` would silently overflow (f up to 2^23 x R up to 2^17 ~ 2^40) and
produce a bogus expected value -- that was a real false failure.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ntt_model import RTLNTT, DILITHIUM_ZETAS

QD = 8380417
BW = 27
M  = 33587228
SH = 48
SCALE_K = 49145
R_MOD   = 131056

# rebuild R=2^27 Montgomery zeta ROM
Rinv_ref = pow(2, -32, QD)
Rm = pow(2, BW, QD)
zetas_m = [(((DILITHIUM_ZETAS[k] % QD) * Rinv_ref) % QD * Rm) % QD for k in range(256)]
def s27(v):
    v %= QD
    return v - (1 << BW) if v >= (1 << (BW - 1)) else v
zeta_unsigned = [s27(z) & ((1 << BW) - 1) for z in zetas_m]

# golden model
d = RTLNTT(q=QD, bw=BW, layers=8, bm=M, bsh=SH, scale_k=SCALE_K)
def to_signed(v):  return [((x + (QD // 2)) % QD) - QD // 2 for x in v]
def red(v):        return [((x % QD) + QD) % QD for x in v]

import random
rng = random.Random(20261022)
f1 = [rng.randint(0, QD - 1) for _ in range(256)]
ntt_f1_signed = d.ntt(zetas_m, to_signed(f1))[0]
ntt_f1_unsigned = [v & ((1 << BW) - 1) for v in ntt_f1_signed]
assert all(-QD//2 <= x <= QD//2 for x in ntt_f1_signed), "forward output must be in [-q/2,q/2]"

# 5 round-trip polynomials
rt_polys = [[rng.randint(0, QD - 1) for _ in range(256)] for _ in range(5)]
rt_flat = [v for p in rt_polys for v in p]

# gold standard: negacyclic convolution  invntt(ntt(a) * ntt(b)) == a*b*R  (mod q)
pa, pb = rt_polys[0], rt_polys[1]
from ntt_model import schoolbook
gold_mul_signed = [s27((v * R_MOD) % QD) for v in schoolbook(pa, pb, QD)]
gold_mul_unsigned = [v & ((1 << BW) - 1) for v in gold_mul_signed]

def emit_array(name, vals, width, idx_width=None):
    """Verilog arrays cannot be range-assigned -> one element per line."""
    return "\n".join("        %s[%d] = %d'd%u;" % (name, i, width, v)
                     for i, v in enumerate(vals))

tb = []
tb.append("`timescale 1ns / 1ps")
tb.append("// Auto-generated by gen_sign_tb.py -- SIGN-mode (Dilithium/ML-DSA) TB for unified_ntt")
tb.append("module tb_unified_ntt_sign;")
tb.append("    localparam QD = 8380417;")
tb.append("    localparam BW = 27;")
tb.append("    localparam R_MOD = 131056;")
tb.append("    reg clk = 0;")
tb.append("    reg rst_n = 0;")
tb.append("    reg start = 0;")
tb.append("    reg inverse = 0;")
tb.append("    wire busy;")
tb.append("    wire done;")
tb.append("    reg load = 0;")
tb.append("    reg [7:0] load_addr = 0;")
tb.append("    reg [BW-1:0] load_data = 0;")
tb.append("    reg [7:0] read_addr = 0;")
tb.append("    wire [BW-1:0] read_data;")
tb.append("    reg zeta_load = 0;")
tb.append("    reg [7:0] zeta_addr = 0;")
tb.append("    reg [BW-1:0] zeta_data = 0;")
tb.append("")
tb.append("    unified_ntt #(")
tb.append("        .N(256), .N_LAYERS(8), .BW(27),")
tb.append("        .Q(8380417), .QINV(58728449), .R_MOD(131056),")
tb.append("        .SCALE_K(49145), .BARRETT_M(33587228), .BARRETT_SH(48)")
tb.append("    ) dut (")
tb.append("        .clk(clk), .rst_n(rst_n),")
tb.append("        .start(start), .inverse(inverse),")
tb.append("        .busy(busy), .done(done),")
tb.append("        .load(load), .load_addr(load_addr), .load_data(load_data),")
tb.append("        .read_addr(read_addr), .read_data(read_data),")
tb.append("        .zeta_load(zeta_load), .zeta_addr(zeta_addr), .zeta_data(zeta_data)")
tb.append("    );")
tb.append("")
tb.append("    always #5 clk = ~clk;")
tb.append("    integer errors = 0;")
tb.append("    integer i, k, t;")
tb.append("    reg [BW-1:0] test_input [0:255];")
tb.append("    reg [BW-1:0] f1         [0:255];   // pristine copy of the Test-1 polynomial")
tb.append("    reg [BW-1:0] coeff_out  [0:255];")
tb.append("    reg [BW-1:0] orig_f     [0:255];")
tb.append("")
tb.append("    // 256-entry Dilithium zeta ROM (R=2^27 Montgomery form)")
tb.append("    reg [BW-1:0] sign_zeta [0:255];")
tb.append("    initial begin")
tb.append(emit_array("sign_zeta", zeta_unsigned, BW))
tb.append("    end")
tb.append("    // Golden forward NTT(f1) -- bit-exact expected DUT output")
tb.append("    reg [BW-1:0] gold_ntt [0:255];")
tb.append("    initial begin")
tb.append(emit_array("gold_ntt", ntt_f1_unsigned, BW))
tb.append("    end")
tb.append("    // 5 round-trip polynomials (flat)")
tb.append("    reg [BW-1:0] rt_poly [0:%d];" % (5*256-1))
tb.append("    initial begin")
tb.append(emit_array("rt_poly", rt_flat, BW))
tb.append("    end")
tb.append("    // scratch for the pointwise product / poly-mul test")
tb.append("    reg [BW-1:0] av [0:255];")
tb.append("    reg [BW-1:0] bv [0:255];")
tb.append("    reg [BW-1:0] pt [0:255];")
tb.append("    // gold standard: schoolbook negacyclic convolution * R (mod q)")
tb.append("    reg [BW-1:0] gold_mul [0:255];")
tb.append("    initial begin")
tb.append(emit_array("gold_mul", gold_mul_unsigned, BW))
tb.append("    end")
tb.append("")
tb.append("    task wait_done;")
tb.append("        integer guard;")
tb.append("        begin")
tb.append("            guard = 0;")
tb.append("            while (!done && guard < 500000) begin @(posedge clk); guard = guard + 1; end")
tb.append("            if (guard >= 500000) begin $display(\"ERROR: Timeout\"); errors = errors + 1; end")
tb.append("        end")
tb.append("    endtask")
tb.append("    task load_poly;")
tb.append("        begin")
tb.append("            for (k = 0; k < 256; k = k + 1) begin")
tb.append("                load_addr = k[7:0]; load_data = test_input[k]; load = 1; @(posedge clk);")
tb.append("            end")
tb.append("            load = 0;")
tb.append("        end")
tb.append("    endtask")
tb.append("    task read_poly;")
tb.append("        begin")
tb.append("            for (k = 0; k < 256; k = k + 1) begin")
tb.append("                read_addr = k[7:0]; @(posedge clk); coeff_out[k] = read_data;")
tb.append("            end")
tb.append("        end")
tb.append("    endtask")
tb.append("    task load_zeta_rom;")
tb.append("        begin")
tb.append("            for (i = 0; i < 256; i = i + 1) begin")
tb.append("                zeta_addr = i[7:0]; zeta_data = sign_zeta[i]; zeta_load = 1; @(posedge clk); zeta_load = 0;")
tb.append("            end")
tb.append("        end")
tb.append("    endtask")
tb.append("")
tb.append("    // main test sequence (f1 population first: no initial-order races)")
tb.append("    initial begin")
tb.append("        rst_n = 0; repeat (5) @(posedge clk); rst_n = 1; repeat (2) @(posedge clk);")
tb.append(emit_array("test_input", f1, BW))
tb.append("\n".join("        f1[%d] = test_input[%d];" % (i, i) for i in range(256)))
tb.append("        $display(\"=== Loading Dilithium zeta ROM (256 entries) ===\");")
tb.append("        load_zeta_rom();")
tb.append("        $display(\"  Zeta ROM loaded OK\");")
tb.append("")
tb.append("        // ---- Test 1: forward NTT bit-exact vs golden ----")
tb.append("        $display(\"\\n=== Test 1: Forward NTT bit-exact vs golden ===\");")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 0; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        errors = 0;")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            if (coeff_out[i] !== gold_ntt[i]) begin")
tb.append("                if (errors < 8) $display(\"MISMATCH[%0d]: got %0d expected %0d\", i, $signed(coeff_out[i]), $signed(gold_ntt[i]));")
tb.append("                errors = errors + 1; end")
tb.append("        end")
tb.append("        if (errors == 0) $display(\"  PASS: forward NTT bit-exact (256/256)\");")
tb.append("        else $display(\"  FAIL: %0d mismatches\", errors);")
tb.append("")
tb.append("        // ---- Test 2: forward range ----")
tb.append("        errors = 0;")
tb.append("        for (i = 0; i < 256; i = i + 1)")
tb.append("            if ($signed(coeff_out[i]) < -(QD/2) || $signed(coeff_out[i]) > QD/2) errors = errors + 1;")
tb.append("        if (errors == 0) $display(\"  PASS: all coeffs in [-q/2,q/2]\");")
tb.append("        else $display(\"  FAIL: %0d out of range\", errors);")
tb.append("")
tb.append("        // ---- Test 3: round-trip invntt(ntt(f)) == f*R mod q ----")
tb.append("        $display(\"\\n=== Test 3: NTT/INTT round-trip (5 polys) ===\");")
tb.append("        errors = 0;")
tb.append("        for (t = 0; t < 5; t = t + 1) begin")
tb.append("            for (i = 0; i < 256; i = i + 1) begin")
tb.append("                test_input[i] = rt_poly[t*256 + i];")
tb.append("                orig_f[i]     = rt_poly[t*256 + i];")
tb.append("            end")
tb.append("            load_poly();")
tb.append("            start = 1; inverse = 0; @(posedge clk); start = 0;")
tb.append("            wait_done(); read_poly();")
tb.append("            for (i = 0; i < 256; i = i + 1) test_input[i] = coeff_out[i];")
tb.append("            load_poly();")
tb.append("            start = 1; inverse = 1; @(posedge clk); start = 0;")
tb.append("            wait_done(); read_poly();")
tb.append("            for (i = 0; i < 256; i = i + 1) begin")
tb.append("                reg [31:0] exp, got;")
tb.append("                reg [63:0] prod64;")
tb.append("                prod64 = orig_f[i] * R_MOD;          // f*R needs 27+17=44 bits; 32-bit would overflow")
tb.append("                exp = prod64 % QD;")
tb.append("                got = ((($signed(coeff_out[i]) % QD) + QD) % QD);")
tb.append("                if (got != exp) begin")
tb.append("                    if (errors < 8) $display(\"RT-MISMATCH poly %0d [%0d]: got %0d exp %0d\", t, i, got, exp);")
tb.append("                    errors = errors + 1; end")
tb.append("            end")
tb.append("        end")
tb.append("        if (errors == 0) $display(\"  PASS: invntt(ntt(f))==f*R mod q (5/5 polys)\");")
tb.append("        else $display(\"  FAIL: %0d mismatches\", errors);")
tb.append("")
tb.append("        // ---- Test 4: INTT(0) == 0 ----")
tb.append("        $display(\"\\n=== Test 4: INTT(0) ===\");")
tb.append("        for (i = 0; i < 256; i = i + 1) test_input[i] = {BW{1'b0}};")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 0; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        for (i = 0; i < 256; i = i + 1) test_input[i] = coeff_out[i];")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 1; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        errors = 0;")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            reg [31:0] got; got = ((($signed(coeff_out[i]) % QD) + QD) % QD);")
tb.append("            if (got != 0) errors = errors + 1;")
tb.append("        end")
tb.append("        if (errors == 0) $display(\"  PASS: invntt(ntt(0)) == 0\");")
tb.append("        else $display(\"  FAIL: %0d non-zero\", errors);")
tb.append("")
tb.append("        // ---- Test 5: INTT of the VERIFIED forward vector (isolates INTT) ----")
tb.append("        $display(\"\\n=== Test 5: INTT(gold_ntt) == f1*R (isolated inverse) ===\");")
tb.append("        for (i = 0; i < 256; i = i + 1) test_input[i] = gold_ntt[i];")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 1; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        errors = 0;")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            reg [31:0] exp5, got5;")
tb.append("            reg [63:0] prod64;")
tb.append("            prod64 = f1[i] * R_MOD;                  // f*R needs 27+17=44 bits; 32-bit would overflow")
tb.append("            exp5 = prod64 % QD;")
tb.append("            got5 = ((($signed(coeff_out[i]) % QD) + QD) % QD);")
tb.append("            if (got5 != exp5) begin")
tb.append("                if (errors < 10) $display(\"INTT-MISMATCH[%0d]: got %0d exp %0d\", i, got5, exp5);")
tb.append("                errors = errors + 1; end")
tb.append("        end")
tb.append("        if (errors == 0) $display(\"  PASS: INTT(gold_ntt) == f1*R (256/256)\");")
tb.append("        else $display(\"  FAIL: %0d mismatches\", errors);")
tb.append("")
tb.append("")
tb.append("        // ---- Test 6: GOLD STANDARD -- invntt(ntt(a) o ntt(b)) == a*b*R ----")
tb.append("        // plain pointwise product (not fqmul): the mathematical NTT is")
tb.append("        // multiplicative, so the full INTT must return the negacyclic")
tb.append("        // convolution times R.  This is the real application property.")
tb.append("        $display(\"\\n=== Test 6: poly_mul == schoolbook negacyclic conv * R ===\");")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            test_input[i] = rt_poly[i];")
tb.append("        end")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 0; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        for (i = 0; i < 256; i = i + 1) av[i] = coeff_out[i];")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            test_input[i] = rt_poly[256 + i];")
tb.append("        end")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 0; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        for (i = 0; i < 256; i = i + 1) bv[i] = coeff_out[i];")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            reg [31:0] ua, ub;")
tb.append("            reg [63:0] pr;")
tb.append("            ua = ((($signed(av[i]) % QD) + QD) % QD);")
tb.append("            ub = ((($signed(bv[i]) % QD) + QD) % QD);")
tb.append("            pr = ua * ub;")
tb.append("            pt[i] = (pr % QD);")
tb.append("        end")
tb.append("        for (i = 0; i < 256; i = i + 1) test_input[i] = pt[i];")
tb.append("        load_poly();")
tb.append("        start = 1; inverse = 1; @(posedge clk); start = 0;")
tb.append("        wait_done(); read_poly();")
tb.append("        errors = 0;")
tb.append("        for (i = 0; i < 256; i = i + 1) begin")
tb.append("            reg [31:0] gu, xu;")
tb.append("            reg [63:0] gp;")
tb.append("            gu = ((($signed(gold_mul[i]) % QD) + QD) % QD);")
tb.append("            gp = $signed(coeff_out[i]) % QD;")
tb.append("            xu = ((gp + QD) % QD);")
tb.append("            if (xu != gu) begin")
tb.append("                if (errors < 8) $display(\"MUL-MISMATCH[%0d]: got %0d expected %0d\", i, xu, gu);")
tb.append("                errors = errors + 1; end")
tb.append("        end")
tb.append("        if (errors == 0) $display(\"  PASS: poly_mul == schoolbook conv * R (256/256)\");")
tb.append("        else $display(\"  FAIL: %0d mismatches\", errors);")
tb.append("")
tb.append("        $display(\"\\n=== SIGN-mode tests done ===\");")
tb.append("        $finish;")
tb.append("    end")
tb.append("endmodule")

with open(os.path.join(HERE, "..", "sim", "tb_unified_ntt_sign.v"), "w") as fh:
    fh.write("\n".join(tb) + "\n")
print("wrote", os.path.abspath(os.path.join(HERE, "..", "sim", "tb_unified_ntt_sign.v")), "(%d lines)" % len(tb))
print("f1[:4]        =", f1[:4])
print("gold_ntt[:4]  =", ntt_f1_signed[:4], "(signed)")
print("rt_polys[0][:3]=", rt_polys[0][:3])
